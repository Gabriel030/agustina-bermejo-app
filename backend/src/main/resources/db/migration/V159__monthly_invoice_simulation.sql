alter table monthly_invoice_run drop constraint ck_monthly_invoice_run_mode;
alter table monthly_invoice_run add constraint ck_monthly_invoice_run_mode check (mode in ('REAL', 'SIMULATION'));
alter table monthly_invoice_run drop constraint ck_monthly_invoice_run_trigger;
alter table monthly_invoice_run add constraint ck_monthly_invoice_run_trigger check (trigger in ('SCHEDULED', 'MANUAL'));

create unique index uq_monthly_invoice_run_simulation_day on monthly_invoice_run (period, business_date) where mode = 'SIMULATION';

create table monthly_invoice_simulation_line (
    id bigint generated by default as identity,
    monthly_invoice_run_id bigint not null,
    enrollment_type varchar(10) not null,
    enrollment_id bigint not null,
    offering_id bigint,
    result varchar(20) not null,
    decision_code varchar(60),
    error_code varchar(60),
    message varchar(500),
    charge_count int not null default 0,
    total_amount numeric(12, 2),
    total_currency varchar(3),
    primary key (id),
    constraint fk_monthly_invoice_simulation_line_run foreign key (monthly_invoice_run_id) references monthly_invoice_run (id) on delete cascade,
    constraint uq_monthly_invoice_simulation_line unique (monthly_invoice_run_id, enrollment_type, enrollment_id),
    constraint ck_monthly_invoice_simulation_line_type check (enrollment_type in ('PROGRAM', 'COURSE')),
    constraint ck_monthly_invoice_simulation_line_result check (result in ('ISSUED', 'NOT_APPLICABLE', 'ALREADY_ISSUED', 'FAILED')),
    constraint ck_monthly_invoice_simulation_line_charges check (charge_count >= 0),
    constraint ck_monthly_invoice_simulation_line_total check (total_amount is null or total_amount >= 0),
    constraint ck_monthly_invoice_simulation_line_total_pair check ((total_amount is null) = (total_currency is null))
);

create table monthly_invoice_simulation_alert (
    id bigint generated by default as identity,
    monthly_invoice_run_id bigint not null,
    alert_type varchar(30) not null,
    enrollment_type varchar(10) not null,
    offering_id bigint not null,
    affected_enrollments int not null,
    message varchar(500) not null,
    primary key (id),
    constraint fk_monthly_invoice_simulation_alert_run foreign key (monthly_invoice_run_id) references monthly_invoice_run (id) on delete cascade,
    constraint uq_monthly_invoice_simulation_alert unique (monthly_invoice_run_id, alert_type, enrollment_type, offering_id),
    constraint ck_monthly_invoice_simulation_alert_type check (alert_type in ('YEAR_NOT_CONFIGURED', 'PRICE_MISSING', 'EMISSION_ERROR', 'ATYPICAL_INCREASE')),
    constraint ck_monthly_invoice_simulation_alert_enrollment_type check (enrollment_type in ('PROGRAM', 'COURSE')),
    constraint ck_monthly_invoice_simulation_alert_affected check (affected_enrollments >= 1)
);
