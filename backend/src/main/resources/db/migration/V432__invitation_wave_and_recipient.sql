create table invitation_wave (
    id bigint generated by default as identity primary key,
    name varchar(160) not null,
    status varchar(20) not null,
    batch_size integer not null,
    interval_minutes integer not null,
    daily_cap integer not null,
    import_batch_id bigint,
    created_by_person_id bigint not null references person (id),
    created_at timestamptz not null,
    started_at timestamptz,
    paused_at timestamptz,
    completed_at timestamptz,
    cancelled_at timestamptz,
    sent_total integer not null default 0,
    failed_total integer not null default 0,
    excluded_total integer not null default 0,
    activated_total integer not null default 0,
    version bigint not null default 0,
    constraint invitation_wave_status_enum check (status in ('DRAFT', 'RUNNING', 'PAUSED', 'COMPLETED', 'CANCELLED')),
    constraint ck_invitation_wave_batch_size check (batch_size > 0),
    constraint ck_invitation_wave_interval_minutes check (interval_minutes > 0),
    constraint ck_invitation_wave_daily_cap check (daily_cap > 0)
);

create index ix_invitation_wave_status on invitation_wave (status);
create index ix_invitation_wave_created_by on invitation_wave (created_by_person_id);

create table invitation_wave_recipient (
    id bigint generated by default as identity primary key,
    wave_id bigint not null references invitation_wave (id),
    person_id bigint not null references person (id),
    status varchar(20) not null,
    exclusion_reason varchar(20),
    delivery_id bigint,
    attempts integer not null default 0,
    last_error varchar(500),
    sent_at timestamptz,
    constraint uq_invitation_wave_recipient unique (wave_id, person_id),
    constraint invitation_wave_recipient_status_enum check (status in ('PENDING', 'QUEUED', 'SENT', 'FAILED', 'ACTIVATED', 'EXCLUDED')),
    constraint invitation_wave_recipient_exclusion_reason_enum check (exclusion_reason in ('NO_EMAIL', 'ALREADY_ACTIVE', 'NOT_ELIGIBLE')),
    constraint ck_invitation_wave_recipient_reason check ((status = 'EXCLUDED') = (exclusion_reason is not null))
);

create index ix_invitation_wave_recipient_status on invitation_wave_recipient (wave_id, status);
create index ix_invitation_wave_recipient_person on invitation_wave_recipient (person_id);
