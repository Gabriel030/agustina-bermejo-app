-- Épica 8 Fase 1: modelo de precios, mora y becas. Todas las entidades de precio/
-- política se versionan por fila nueva (nunca UPDATE sobre una vigente) — el
-- historial completo queda en la tabla misma, sin necesitar una tabla de
-- auditoría aparte (createdBy/createdAt en cada una).

-- Matrícula (solo carrera) y cuota mensual (carrera o curso) son conceptos de
-- precio independientes — ver decisión de negocio "para darte de alta en una
-- carrera pagás matrícula, para un curso directamente la cuota del primer mes".
create table fee_schedule (
    id bigint generated by default as identity, version bigint not null default 0,
    program_id bigint, course_id bigint,
    concept varchar(20) not null,
    amount numeric(12,2) not null,
    vigente_desde date not null,
    created_by_id bigint not null, created_at timestamp(6) not null,
    primary key (id),
    constraint fk_fee_schedule_program foreign key (program_id) references program,
    constraint fk_fee_schedule_course foreign key (course_id) references course,
    constraint fk_fee_schedule_created_by foreign key (created_by_id) references person,
    constraint chk_fee_schedule_single_target check (
        (program_id is not null and course_id is null)
        or
        (program_id is null and course_id is not null)
    )
);

create index ix_fee_schedule_program on fee_schedule (program_id, concept, vigente_desde);
create index ix_fee_schedule_course on fee_schedule (course_id, concept, vigente_desde);

-- Institucional única (decisión de negocio: no configurable por carrera/curso) —
-- una fila nueva por cambio, la vigente es la de vigente_desde <= hoy más reciente.
create table late_fee_policy (
    id bigint generated by default as identity, version bigint not null default 0,
    dias_de_gracia integer not null,
    porcentaje_recargo_por_periodo numeric(5,2) not null,
    dias_por_periodo integer not null,
    dias_para_riesgo_de_corte integer not null,
    vigente_desde date not null,
    created_by_id bigint not null, created_at timestamp(6) not null,
    primary key (id),
    constraint fk_late_fee_policy_created_by foreign key (created_by_id) references person
);

create table billing_period (
    id bigint generated by default as identity, version bigint not null default 0,
    dia_inicio integer not null, dia_fin integer not null,
    vigente_desde date not null,
    created_by_id bigint not null, created_at timestamp(6) not null,
    primary key (id),
    constraint fk_billing_period_created_by foreign key (created_by_id) references person
);

-- Beca/descuento individual — se suma con cualquier Promotion aplicable al mismo alumno.
create table discount (
    id bigint generated by default as identity, version bigint not null default 0,
    student_id bigint not null,
    tipo varchar(20) not null,
    valor numeric(12,2) not null,
    vigente_desde date not null, vigente_hasta date,
    motivo varchar(500) not null,
    created_by_id bigint not null, created_at timestamp(6) not null,
    primary key (id),
    constraint fk_discount_student foreign key (student_id) references student,
    constraint fk_discount_created_by foreign key (created_by_id) references person
);

create index ix_discount_student on discount (student_id);

-- Promoción segmentada — al menos uno de program_id/course_id (el otro criterio de
-- segmentación es el propio rango vigente_desde/vigente_hasta, siempre presente).
create table promotion (
    id bigint generated by default as identity, version bigint not null default 0,
    program_id bigint, course_id bigint,
    tipo varchar(20) not null,
    valor numeric(12,2) not null,
    vigente_desde date not null, vigente_hasta date,
    created_by_id bigint not null, created_at timestamp(6) not null,
    primary key (id),
    constraint fk_promotion_program foreign key (program_id) references program,
    constraint fk_promotion_course foreign key (course_id) references course,
    constraint fk_promotion_created_by foreign key (created_by_id) references person,
    constraint chk_promotion_at_least_one_target check (program_id is not null or course_id is not null)
);

create index ix_promotion_program on promotion (program_id, vigente_desde, vigente_hasta);
create index ix_promotion_course on promotion (course_id, vigente_desde, vigente_hasta);

-- Comprobante subido por el propio Alumno — paso previo sin confirmar (mismo
-- criterio que Prospect es un paso previo a Student), nunca un Payment real hasta
-- que alguien de staff lo aprueba.
create table payment_receipt (
    id bigint generated by default as identity, version bigint not null default 0,
    invoice_id bigint not null,
    file_path varchar(500) not null,
    uploaded_at timestamp(6) not null,
    status varchar(20) not null,
    rejection_reason varchar(500),
    reviewed_by_id bigint, reviewed_at timestamp(6),
    primary key (id),
    constraint fk_payment_receipt_invoice foreign key (invoice_id) references invoice,
    constraint fk_payment_receipt_reviewed_by foreign key (reviewed_by_id) references person
);

-- Un Invoice no puede tener dos comprobantes en revisión al mismo tiempo — evita
-- que el Alumno suba dos comprobantes distintos mientras el primero sigue abierto.
create unique index uk_payment_receipt_pending on payment_receipt (invoice_id)
    where status = 'PENDING_REVIEW';

create index ix_payment_receipt_status on payment_receipt (status);
