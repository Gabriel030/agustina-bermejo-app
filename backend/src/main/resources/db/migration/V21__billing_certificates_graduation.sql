alter table student drop column defaulter;

alter table term add column enrollment_override varchar(20);

create table invoice (
    id bigint generated by default as identity, version bigint not null default 0,
    student_id bigint not null,
    concept varchar(255) not null, amount numeric(12,2) not null,
    due_date date not null, issued_at timestamp(6) not null,
    status varchar(20) not null,
    primary key (id),
    constraint fk_invoice_student foreign key (student_id) references student
);

create table payment (
    id bigint generated by default as identity, version bigint not null default 0,
    invoice_id bigint not null,
    amount numeric(12,2) not null, paid_at timestamp(6) not null,
    method varchar(20) not null, registered_by_id bigint not null,
    notes varchar(500),
    primary key (id),
    constraint fk_payment_invoice foreign key (invoice_id) references invoice,
    constraint fk_payment_registered_by foreign key (registered_by_id) references person
);

create table graduation_request (
    id bigint generated by default as identity, version bigint not null default 0,
    program_enrollment_id bigint not null,
    status varchar(20) not null, requested_at timestamp(6) not null,
    verified_by_id bigint, verified_at timestamp(6),
    decided_by_id bigint, decided_at timestamp(6), rejection_reason varchar(500),
    primary key (id),
    constraint fk_graduation_request_program_enr foreign key (program_enrollment_id) references program_enrollment,
    constraint fk_graduation_request_verified_by foreign key (verified_by_id) references person,
    constraint fk_graduation_request_decided_by foreign key (decided_by_id) references person
);

-- Decisión 11: un solo trámite activo (no rechazado) por ProgramEnrollment a la vez.
create unique index uk_graduation_request_active on graduation_request (program_enrollment_id)
    where status <> 'REJECTED';

create table director_approval_request (
    id bigint generated by default as identity, version bigint not null default 0,
    type varchar(30) not null,
    program_enrollment_id bigint not null, subject_id bigint,
    justification varchar(1000) not null, status varchar(20) not null,
    requested_by_id bigint not null, requested_at timestamp(6) not null,
    decided_by_id bigint, decided_at timestamp(6), decision_notes varchar(500),
    primary key (id),
    constraint fk_dar_program_enr foreign key (program_enrollment_id) references program_enrollment,
    constraint fk_dar_subject foreign key (subject_id) references subject,
    constraint fk_dar_requested_by foreign key (requested_by_id) references person,
    constraint fk_dar_decided_by foreign key (decided_by_id) references person
);

