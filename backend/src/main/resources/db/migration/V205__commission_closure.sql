create sequence closure_report_number_seq;

create table commission_closure (
    id bigint generated by default as identity primary key,
    section_kind varchar(20) not null,
    section_id bigint not null,
    status varchar(30) not null,
    report_version integer not null default 1,
    report_number varchar(20),
    book varchar(50),
    folio varchar(50),
    confirmed_by_id bigint references person (id),
    confirmed_at timestamp(6),
    delivered_at timestamp(6),
    closed_by_id bigint references person (id),
    closed_at timestamp(6),
    closed_without_teacher_confirmation boolean not null default false,
    lock_version bigint not null default 0,
    constraint uq_commission_closure_section unique (section_kind, section_id),
    constraint uq_commission_closure_report_number unique (report_number),
    constraint ck_commission_closure_section_kind check (section_kind in ('PROGRAM', 'COURSE')),
    constraint ck_commission_closure_status check (status in ('DRAFT_AVAILABLE', 'TEACHER_CONFIRMED', 'CLOSED', 'REOPENED')),
    constraint ck_commission_closure_report_version check (report_version >= 1),
    constraint ck_commission_closure_closed_has_report check (
        status <> 'CLOSED'
        or (report_number is not null and book is not null and folio is not null
            and closed_by_id is not null and closed_at is not null))
);

create table commission_closure_student (
    id bigint generated by default as identity primary key,
    closure_id bigint not null references commission_closure (id),
    enrollment_id bigint not null,
    final_condition varchar(30) not null,
    promotion_grade numeric(4,2) check (promotion_grade is null or promotion_grade between 1 and 10),
    attendance_ok boolean,
    grade_ok boolean,
    administrative_ok boolean,
    documents_complete boolean,
    correlatives_ok boolean,
    teacher_observation varchar(500),
    constraint uq_commission_closure_student unique (closure_id, enrollment_id),
    constraint ck_commission_closure_student_condition check (
        final_condition in ('PROMOTES', 'PROMOTION_CONDITIONAL', 'GOES_TO_FINAL', 'FREE', 'FAILED')),
    constraint ck_commission_closure_student_promotion_grade check (
        final_condition not in ('PROMOTES', 'PROMOTION_CONDITIONAL') or promotion_grade is not null)
);

create table commission_closure_audit (
    id bigint generated by default as identity primary key,
    closure_id bigint not null references commission_closure (id),
    action varchar(40) not null,
    report_version integer not null,
    actor_person_id bigint not null references person (id),
    reason varchar(500),
    occurred_at timestamp(6) not null,
    constraint ck_commission_closure_audit_action check (
        action in ('CONFIRMED_BY_TEACHER', 'CLOSED', 'CLOSED_WITHOUT_TEACHER_CONFIRMATION', 'REOPENED'))
);

create index ix_commission_closure_audit_closure on commission_closure_audit (closure_id);
