create table subject_equivalence (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    program_enrollment_id bigint not null references program_enrollment (id),
    subject_id bigint not null references subject (id),
    student_document_id bigint references student_document (id),
    origin_institution varchar(255) not null,
    origin_subject_name varchar(255) not null,
    origin_score numeric(4, 2),
    recognized_on date not null,
    resolution_number varchar(100) not null,
    reason varchar(1000),
    status varchar(20) not null,
    recorded_by_id bigint not null references person (id),
    recorded_at timestamp(6) not null,
    voided_by_id bigint references person (id),
    voided_at timestamp(6),
    void_reason varchar(1000),
    constraint subject_equivalence_status_enum check (status in ('ACTIVE', 'VOIDED')),
    constraint ck_subject_equivalence_origin_score check (origin_score is null or origin_score between 0 and 10),
    constraint ck_subject_equivalence_resolution_number check (length(trim(resolution_number)) > 0),
    constraint ck_subject_equivalence_void_consistency check (
        (status = 'ACTIVE' and voided_by_id is null and voided_at is null and void_reason is null)
        or (status = 'VOIDED' and voided_by_id is not null and voided_at is not null and void_reason is not null))
);

create unique index uk_subject_equivalence_active
    on subject_equivalence (program_enrollment_id, subject_id) where status = 'ACTIVE';
create index ix_subject_equivalence_enrollment on subject_equivalence (program_enrollment_id);
create index ix_subject_equivalence_subject on subject_equivalence (subject_id);
create index ix_subject_equivalence_student_document on subject_equivalence (student_document_id);

do $$
declare
    action_literals text;
    entity_type_literals text;
begin
    select string_agg(distinct quote_literal(m[1]), ', ') into action_literals
    from pg_constraint c, regexp_matches(pg_get_constraintdef(c.oid), '''([A-Z_]+)''', 'g') as m
    where c.conname = 'ck_audit_log_action' and c.conrelid = 'audit_log'::regclass;
    select string_agg(distinct quote_literal(m[1]), ', ') into entity_type_literals
    from pg_constraint c, regexp_matches(pg_get_constraintdef(c.oid), '''([A-Z_]+)''', 'g') as m
    where c.conname = 'ck_audit_log_entity_type' and c.conrelid = 'audit_log'::regclass;
    execute 'alter table audit_log drop constraint ck_audit_log_action';
    execute 'alter table audit_log add constraint ck_audit_log_action check (action in (' || action_literals
        || ', ''SUBJECT_EQUIVALENCE_RECORDED'', ''SUBJECT_EQUIVALENCE_VOIDED'')) not valid';
    execute 'alter table audit_log drop constraint ck_audit_log_entity_type';
    execute 'alter table audit_log add constraint ck_audit_log_entity_type check (entity_type in (' || entity_type_literals
        || ', ''SUBJECT_EQUIVALENCE'')) not valid';
end $$;
alter table audit_log validate constraint ck_audit_log_action;
