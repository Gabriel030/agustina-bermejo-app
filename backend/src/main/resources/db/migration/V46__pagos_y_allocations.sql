-- Fase 6.2 (Pagos y allocations): completa PaymentAllocation/PaymentReceipt con el flujo real
-- (antes eran un puente temporal de Épica 7 Fase 3 — ver reconciliación en la nota de Fase 6.2
-- de Obsidian). payment_allocation nunca tuvo filas hasta ahora (el placeholder anterior de
-- PaymentReceiptService.aprobar() marcaba la Invoice como PAID directo, sin crear ninguna), así
-- que payment_id puede nacer NOT NULL sin backfill.

create table payment (
    id bigint generated by default as identity,
    version bigint,
    amount numeric(12,2) not null,
    method varchar(20) not null,
    registered_by_id bigint not null,
    paid_at timestamp(6) not null,
    status varchar(30) not null,
    rejection_reason varchar(500),
    external_reference varchar(255),
    card_installments integer,
    notes varchar(500),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint fk_payment_registered_by foreign key (registered_by_id) references person
);

-- Idempotencia del webhook de Mercado Pago (se ejercita recién en Fase 6.9, la columna ya nace
-- con el índice para no necesitar otra migración cuando llegue esa fase).
create unique index uk_payment_external_reference on payment (external_reference) where external_reference is not null;

alter table payment_allocation add column payment_id bigint not null references payment;
alter table payment_allocation add column created_at timestamp(6) not null default now();
alter table payment_allocation alter column created_at drop default;

-- Un pago no puede tener dos allocations contra la misma cuota (se corrige editando el monto,
-- no duplicando la fila).
create unique index uk_payment_allocation on payment_allocation (payment_id, invoice_id);

alter table payment_receipt add column uploaded_by_id bigint references person;

-- Una sola en revisión por Invoice a la vez.
create unique index uk_payment_receipt_pending on payment_receipt (invoice_id) where status = 'PENDING_REVIEW';

create table collections_policy (
    id bigint generated by default as identity,
    grace_period_days integer not null,
    surcharge_percentage numeric(5,4) not null,
    suspension_after_days integer not null,
    suspension_after_invoice_count integer not null,
    withdrawal_after_days integer not null,
    withdrawal_after_invoice_count integer not null,
    effective_from date not null,
    created_by_id bigint not null,
    created_at timestamp(6) not null,
    primary key (id),
    constraint fk_collections_policy_created_by foreign key (created_by_id) references person
);

-- Sin esto, el primer arranque no tiene ninguna CollectionsPolicy vigente. Valores default
-- confirmados 2026-09-03: 30/60 días O 2/3 cuotas OVERDUE simultáneas, lo que se cumpla primero.
insert into collections_policy (grace_period_days, surcharge_percentage, suspension_after_days,
    suspension_after_invoice_count, withdrawal_after_days, withdrawal_after_invoice_count, effective_from, created_by_id, created_at)
    select 10, 0.10, 30, 2, 60, 3, current_date, id, now() from person order by id limit 1;
