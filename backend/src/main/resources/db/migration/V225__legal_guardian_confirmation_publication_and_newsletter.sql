create table legal_guardian_confirmation (
    id bigint generated by default as identity primary key,
    person_id bigint not null references person,
    guardian_name varchar(255) not null,
    guardian_email varchar(255) not null,
    guardian_relationship varchar(60) not null,
    token_hash varchar(64) not null unique,
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    used_at timestamp(6)
);

create index ix_legal_guardian_confirmation_person on legal_guardian_confirmation (person_id, created_at desc);

create table legal_document_publication (
    id bigint generated by default as identity primary key,
    document_type varchar(20) not null,
    version varchar(40) not null,
    first_seen_at timestamp(6) not null,
    constraint uq_legal_document_publication_type_version unique (document_type, version)
);

alter table legal_document_publication
    add constraint legal_document_publication_document_type_enum check (document_type in ('PRIVACY', 'TERMS')) not valid;

alter table legal_document_publication validate constraint legal_document_publication_document_type_enum;

create table newsletter_preference (
    person_id bigint primary key references person,
    opted_in boolean not null,
    updated_at timestamp(6) not null
);
