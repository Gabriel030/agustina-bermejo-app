create table curriculum_plan (
    id bigint generated by default as identity primary key,
    program_id bigint not null,
    version_number integer not null,
    name varchar(255) not null,
    status varchar(20) not null,
    valid_from date not null,
    valid_until date,
    graduation_deadline date,
    total_years integer,
    total_credits_required integer not null default 0,
    total_hours_required integer,
    constraint fk_curriculum_plan_program foreign key (program_id) references program (id) on delete cascade,
    constraint uk_curriculum_plan_program_version unique (program_id, version_number)
);

create index idx_curriculum_plan_program_status on curriculum_plan (program_id, status);

insert into curriculum_plan (program_id, version_number, name, status, valid_from, total_years,
                             total_credits_required, total_hours_required)
select p.id, 1, p.name || ' - Plan v1', 'ACTIVE', current_date, p.total_years,
       coalesce(p.total_credits_required, 0), p.total_hours_required
from program p;

alter table program_subject add column plan_id bigint;

update program_subject ps
set plan_id = (select cp.id from curriculum_plan cp where cp.program_id = ps.program_id and cp.version_number = 1);

alter table program_subject alter column plan_id set not null;
alter table program_subject add constraint fk_program_subject_plan
    foreign key (plan_id) references curriculum_plan (id) on delete cascade;
create index idx_program_subject_plan on program_subject (plan_id);
create index idx_program_subject_program on program_subject (program_id);

alter table program_subject drop constraint uk_program_subject_program_subject;
alter table program_subject add constraint uk_program_subject_plan_subject unique (plan_id, subject_id);

create unique index uk_curriculum_plan_one_active_per_program on curriculum_plan (program_id) where status = 'ACTIVE';

alter table curriculum_plan
    add constraint curriculum_plan_status_enum check (status in ('DRAFT', 'ACTIVE', 'EXPIRED')) not valid;
alter table curriculum_plan
    add constraint curriculum_plan_version_positive check (version_number > 0) not valid;
alter table curriculum_plan
    add constraint curriculum_plan_validity_range
        check (valid_until is null or valid_until >= valid_from) not valid;
alter table curriculum_plan
    add constraint curriculum_plan_graduation_deadline_after_validity
        check (graduation_deadline is null or valid_until is null or graduation_deadline >= valid_until) not valid;
alter table curriculum_plan
    add constraint curriculum_plan_totals_not_negative
        check (total_credits_required >= 0 and (total_years is null or total_years >= 0)
               and (total_hours_required is null or total_hours_required >= 0)) not valid;
