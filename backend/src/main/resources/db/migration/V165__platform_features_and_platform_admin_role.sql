create table platform_feature (
    code varchar(40) primary key,
    enabled boolean not null,
    mode varchar(10),
    version bigint not null default 0,
    updated_at timestamp(6) not null,
    updated_by_id bigint references person,
    constraint ck_platform_feature_mode check (mode is null or mode in ('OFF', 'MIRROR', 'FULL')),
    constraint ck_platform_feature_billing_mode check ((code = 'BILLING') = (mode is not null)),
    constraint ck_platform_feature_billing_enabled check (code <> 'BILLING' or enabled = (mode <> 'OFF'))
);

create table feature_change_log (
    id bigint generated by default as identity primary key,
    code varchar(40) not null,
    before_json text,
    after_json text not null,
    actor_person_id bigint references person,
    actor_kind varchar(8) not null,
    reason varchar(500) not null,
    changed_at timestamp(6) not null,
    constraint ck_feature_change_log_actor_kind check (actor_kind in ('HUMAN', 'SERVICE'))
);

create index ix_feature_change_log_changed_at on feature_change_log (changed_at desc, id desc);

