-- Spec Estructura académica. Separa el contenido de una materia (Subject, sin dueño de
-- carrera) de cómo cada carrera la incluye en su plan (program_subject, que pasa a ser
-- Program×Subject). Tablas vacías hoy (no existe servicio que las haya poblado), por eso
-- se puede agregar subject_id NOT NULL directo sin backfill.
create table subject (
    id bigint generated by default as identity,
    name varchar(255) not null,
    description varchar(500),
    status varchar(20) not null default 'ACTIVE',
    primary key (id),
    constraint uk_subject_name unique (name)
);

alter table program_subject add column subject_id bigint not null;
alter table program_subject add constraint fk_program_subject_subject
    foreign key (subject_id) references subject;
alter table program_subject drop column name;
-- Una carrera no puede incluir el mismo Subject dos veces en su plan.
alter table program_subject add constraint uk_program_subject_program_subject
    unique (program_id, subject_id);

-- La comisión (antes atada a program_subject de UNA carrera) pasa a atarse al Subject
-- directamente, para que una sola comisión admita alumnos de cualquier carrera que
-- tenga ese Subject en su plan.
alter table program_section add column subject_id bigint not null;
alter table program_section add constraint fk_program_section_subject
    foreign key (subject_id) references subject;
alter table program_section drop column program_subject_id;
