create table collection_reminder (
    id bigint generated by default as identity primary key,
    student_id bigint not null references student (id),
    business_date date not null,
    in_app_messages jsonb not null default '[]'::jsonb,
    email_messages jsonb not null default '[]'::jsonb,
    suppressed jsonb not null default '[]'::jsonb,
    created_at timestamp(6) not null,
    constraint uq_collection_reminder_student_day unique (student_id, business_date),
    constraint ck_collection_reminder_lists_are_arrays check (jsonb_typeof(in_app_messages) = 'array' and jsonb_typeof(email_messages) = 'array'
        and jsonb_typeof(suppressed) = 'array'),
    constraint ck_collection_reminder_not_empty check (jsonb_array_length(in_app_messages) + jsonb_array_length(email_messages) + jsonb_array_length(suppressed) > 0)
);

create index ix_collection_reminder_business_date on collection_reminder (business_date);

update configuration_version
set config_values = config_values || '{"dailyDigestEnabled": true}'::jsonb
where scope = 'COLLECTION_REMINDERS';
