drop table credit_note;

create sequence credit_note_number_seq;

create table credit_note (
    id bigint generated by default as identity primary key,
    credit_note_number varchar(20) not null,
    student_current_account_id bigint not null,
    currency varchar(3) not null check (currency in ('ARS', 'USD')),
    invoice_id bigint not null,
    invoice_number varchar(20) not null,
    reason varchar(30) not null check (reason in ('BILLING_ERROR', 'CANCELLATION', 'LATE_FEE_ANNULMENT', 'WITHDRAWAL')),
    justification varchar(1000) not null check (length(trim(justification)) > 0),
    offset_amount numeric(12, 2) not null check (offset_amount >= 0),
    offset_amount_currency varchar(3) not null,
    free_credit_amount numeric(12, 2) not null check (free_credit_amount >= 0),
    free_credit_amount_currency varchar(3) not null,
    total_amount numeric(12, 2) not null,
    total_amount_currency varchar(3) not null,
    issue_date date not null,
    fact_date date not null,
    recipient_snapshot jsonb not null,
    authorization_request_id bigint references authorization_request (id),
    issued_by_person_id bigint references person (id),
    issued_by_process varchar(80),
    recorded_at timestamp(6) not null,
    constraint uk_credit_note_number unique (credit_note_number),
    constraint uk_credit_note_id_account unique (id, student_current_account_id),
    constraint fk_credit_note_invoice_account foreign key (invoice_id, student_current_account_id)
        references invoice (id, student_current_account_id),
    constraint fk_credit_note_invoice_currency foreign key (invoice_id, currency) references invoice (id, currency),
    constraint ck_credit_note_number_format check (credit_note_number ~ '^NC-[0-9]{8}$'),
    constraint ck_credit_note_currencies check (offset_amount_currency = currency and free_credit_amount_currency = currency
        and total_amount_currency = currency),
    constraint ck_credit_note_total check (total_amount = offset_amount + free_credit_amount and total_amount > 0),
    constraint ck_credit_note_actor check (num_nonnulls(issued_by_person_id, issued_by_process) = 1)
);

create index ix_credit_note_account on credit_note (student_current_account_id, issue_date desc, id desc);
create index ix_credit_note_invoice on credit_note (invoice_id);

create table credit_note_line (
    id bigint generated by default as identity primary key,
    credit_note_id bigint not null references credit_note (id),
    invoice_line_number integer not null check (invoice_line_number >= 1),
    amount numeric(12, 2) not null check (amount > 0),
    amount_currency varchar(3) not null,
    offset_part numeric(12, 2) not null check (offset_part >= 0),
    offset_part_currency varchar(3) not null,
    free_part numeric(12, 2) not null check (free_part >= 0),
    free_part_currency varchar(3) not null,
    constraint uk_credit_note_line unique (credit_note_id, invoice_line_number),
    constraint ck_credit_note_line_parts check (amount = offset_part + free_part),
    constraint ck_credit_note_line_currencies check (offset_part_currency = amount_currency and free_part_currency = amount_currency)
);

alter table current_account_entry add constraint fk_current_account_entry_credit_note
    foreign key (credit_note_id, student_current_account_id) references credit_note (id, student_current_account_id);

alter table invoice_line drop constraint ck_invoice_line_free_credited_within_net;
alter table invoice_line add constraint ck_invoice_line_total_credited_within_net
    check (credited_amount + free_credited_amount <= amount - discount_amount);

