alter table current_account_entry disable trigger trg_current_account_entry_append_only;

create temporary table legacy_credit_note_entry on commit drop as
select id, student_current_account_id, amount from current_account_entry where credit_note_id is not null;

delete from current_account_entry where credit_note_id is not null;

update student_current_account a
set unallocated_credit_amount = greatest(0, a.unallocated_credit_amount - removed.total)
from (select student_current_account_id, sum(amount) as total from legacy_credit_note_entry group by student_current_account_id) removed
where a.id = removed.student_current_account_id;

update current_account_entry
set sequence_number = sequence_number + 1000000000
where student_current_account_id in (select student_current_account_id from legacy_credit_note_entry);

with renumbered as (
    select id,
           row_number() over (partition by student_current_account_id order by sequence_number) as new_sequence,
           sum(case direction when 'DEBIT' then amount else -amount end)
               over (partition by student_current_account_id order by sequence_number) as running
    from current_account_entry
    where student_current_account_id in (select student_current_account_id from legacy_credit_note_entry))
update current_account_entry e
set sequence_number = r.new_sequence,
    running_balance_amount = abs(r.running),
    running_balance_side = case when r.running > 0 then 'OWES' when r.running < 0 then 'IN_FAVOR' else 'ZERO' end
from renumbered r
where e.id = r.id;

update student_current_account a
set last_entry_sequence = coalesce(last.sequence_number, 0),
    balance_amount = coalesce(last.running_balance_amount, 0),
    balance_side = coalesce(last.running_balance_side, 'ZERO')
from (select distinct student_current_account_id from legacy_credit_note_entry) affected
left join lateral (select sequence_number, running_balance_amount, running_balance_side from current_account_entry e
                   where e.student_current_account_id = affected.student_current_account_id order by sequence_number desc limit 1) last on true
where a.id = affected.student_current_account_id;

