create table institute_setting (
    code varchar(40) primary key,
    enabled boolean not null,
    version bigint not null default 0,
    updated_at timestamp(6) not null,
    updated_by_id bigint references person
);

create table institute_setting_change_log (
    id bigint generated by default as identity primary key,
    code varchar(40) not null,
    before_enabled boolean,
    after_enabled boolean not null,
    actor_person_id bigint references person,
    reason varchar(500) not null,
    changed_at timestamp(6) not null
);

create index ix_institute_setting_change_log_changed_at on institute_setting_change_log (changed_at desc, id desc);

