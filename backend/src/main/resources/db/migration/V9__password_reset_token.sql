-- Spec JWT y login (RF-AUTH-03, parcial). Mismo patrón que refresh_token: token hasheado,
-- expiración corta. "used" en vez de "revoked": el concepto de dominio acá es "consumido"
-- (se usa una vez y se descarta), no "revocado por seguridad".
create table password_reset_token (
    id bigint generated by default as identity,
    person_id bigint not null,
    token_hash varchar(255) not null,
    expires_at timestamp not null,
    used boolean not null default false,
    created_at timestamp not null,
    primary key (id),
    constraint uk_password_reset_token_hash unique (token_hash),
    constraint fk_password_reset_token_person foreign key (person_id) references person on delete cascade
);
