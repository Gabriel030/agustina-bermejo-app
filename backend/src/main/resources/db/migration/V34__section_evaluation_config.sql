-- Configuración variable por comisión (TPs, fechas, flujo de aprobación) separada de
-- EvaluationScheme a propósito: EvaluationScheme es la política institucional reutilizable
-- entre comisiones (mínimos, promoción), esto es 1:1 por comisión y cambia cuatrimestre a
-- cuatrimestre (Spec - Docente, configuración de evaluación y mesas).
create table section_evaluation_config (
    id bigint generated by default as identity,
    version bigint not null default 0,
    subject_section_id bigint not null,
    status varchar(20) not null,
    tp_count integer,
    tp1_due_date date,
    tp2_due_date date,
    tp3_due_date date,
    exam1_date date,
    exam2_date date,
    final_call1_date date,
    final_call2_date date,
    rejection_reason varchar(500),
    submitted_at timestamp(6),
    reviewed_by_id bigint,
    reviewed_at timestamp(6),
    primary key (id),
    constraint uk_section_eval_config_section unique (subject_section_id),
    constraint fk_section_eval_config_section foreign key (subject_section_id) references subject_section,
    constraint fk_section_eval_config_reviewed_by foreign key (reviewed_by_id) references person
);
