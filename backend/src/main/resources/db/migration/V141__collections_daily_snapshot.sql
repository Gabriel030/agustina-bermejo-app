create table collections_daily_snapshot (
    id bigint generated by default as identity,
    business_date date not null,
    currency varchar(3) not null,
    program_id bigint,
    course_id bigint,
    overdue_1_30 numeric(12, 2) not null check (overdue_1_30 >= 0),
    overdue_31_60 numeric(12, 2) not null check (overdue_31_60 >= 0),
    overdue_61_90 numeric(12, 2) not null check (overdue_61_90 >= 0),
    overdue_90_plus numeric(12, 2) not null check (overdue_90_plus >= 0),
    students_with_overdue integer not null check (students_with_overdue >= 0),
    enrollments_suspended integer check (enrollments_suspended >= 0),
    unallocated_credit_amount numeric(12, 2) check (unallocated_credit_amount >= 0),
    created_at timestamp(6) not null,
    primary key (id),
    constraint ck_collections_daily_snapshot_currency check (currency in ('ARS', 'USD')),
    constraint ck_collections_daily_snapshot_single_scope check (program_id is null or course_id is null)
);

create unique index ux_collections_daily_snapshot_scope
    on collections_daily_snapshot (business_date, currency, coalesce(program_id, 0), coalesce(course_id, 0));

create index ix_collections_daily_snapshot_total_by_date
    on collections_daily_snapshot (currency, business_date)
    where program_id is null and course_id is null;
