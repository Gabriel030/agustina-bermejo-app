alter table notification add column dedup_key varchar(120);

create unique index uq_notification_dedup_key on notification (dedup_key) where dedup_key is not null;

create table notification_delivery (
    id bigint generated by default as identity primary key,
    dedup_key varchar(120) not null,
    channel varchar(10) not null check (channel in ('IN_APP', 'EMAIL')),
    category varchar(30) not null check (category in ('COLLECTION_REMINDER')),
    kind varchar(64) not null,
    priority integer not null check (priority >= 1),
    recipient_person_id bigint not null references person (id),
    related_entity_type varchar(60),
    related_entity_id bigint,
    status varchar(20) not null check (status in ('QUEUED', 'SENT', 'SENT_SIMULATED', 'SUPPRESSED', 'DEFERRED', 'DISCARDED', 'FAILED')),
    status_reason varchar(60),
    scheduled_for date not null,
    not_before timestamptz,
    attempts integer not null default 0 check (attempts >= 0),
    provider_message_id varchar(120),
    subject varchar(300),
    body_text text not null,
    body_html text,
    sent_at timestamptz,
    created_at timestamptz not null,
    constraint uq_notification_delivery_dedup unique (dedup_key, channel),
    constraint ck_notification_delivery_reason_required
        check (status not in ('SUPPRESSED', 'DEFERRED', 'DISCARDED', 'FAILED') or status_reason is not null),
    constraint ck_notification_delivery_email_subject
        check (channel <> 'EMAIL' or subject is not null),
    constraint ck_notification_delivery_sent_at
        check (status not in ('SENT', 'SENT_SIMULATED') or sent_at is not null),
    constraint ck_notification_delivery_simulated_is_email
        check (status <> 'SENT_SIMULATED' or channel = 'EMAIL')
);

create index idx_notification_delivery_dispatch on notification_delivery (channel, status, scheduled_for);
create index idx_notification_delivery_recipient on notification_delivery (recipient_person_id);
