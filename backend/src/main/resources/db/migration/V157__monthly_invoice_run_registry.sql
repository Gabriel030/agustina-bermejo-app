create table monthly_invoice_run (
    id bigint generated by default as identity,
    period date not null,
    mode varchar(12) not null,
    issuance_mode varchar(10) not null,
    business_date date not null,
    pricing_date date not null,
    status varchar(30) not null,
    trigger varchar(12) not null,
    failure_code varchar(60),
    started_at timestamp(6) not null,
    finished_at timestamp(6),
    primary key (id),
    constraint ck_monthly_invoice_run_mode check (mode in ('REAL')),
    constraint ck_monthly_invoice_run_issuance_mode check (issuance_mode in ('DIRECT')),
    constraint ck_monthly_invoice_run_status check (status in ('RUNNING', 'COMPLETED', 'COMPLETED_WITH_FAILURES', 'FAILED')),
    constraint ck_monthly_invoice_run_trigger check (trigger in ('SCHEDULED')),
    constraint ck_monthly_invoice_run_finished check ((status = 'RUNNING') = (finished_at is null)),
    constraint ck_monthly_invoice_run_failure check ((status = 'FAILED') = (failure_code is not null))
);

create unique index uq_monthly_invoice_run_real_period on monthly_invoice_run (period) where mode = 'REAL' and status <> 'FAILED';

create table monthly_invoice_run_item (
    id bigint generated by default as identity,
    monthly_invoice_run_id bigint not null,
    enrollment_type varchar(10) not null,
    enrollment_id bigint not null,
    result varchar(20) not null,
    decision_code varchar(60),
    error_code varchar(60),
    message varchar(500),
    attempts int not null default 0,
    next_retry_at timestamp(6),
    invoice_ids bigint[],
    primary key (id),
    constraint fk_monthly_invoice_run_item_run foreign key (monthly_invoice_run_id) references monthly_invoice_run (id),
    constraint uq_monthly_invoice_run_item unique (monthly_invoice_run_id, enrollment_type, enrollment_id),
    constraint ck_monthly_invoice_run_item_type check (enrollment_type in ('PROGRAM', 'COURSE')),
    constraint ck_monthly_invoice_run_item_result check (result in ('ISSUED', 'NOT_APPLICABLE', 'ALREADY_ISSUED', 'FAILED')),
    constraint ck_monthly_invoice_run_item_attempts check (attempts >= 0)
);

create index ix_monthly_invoice_run_item_retry on monthly_invoice_run_item (next_retry_at) where result = 'FAILED';
