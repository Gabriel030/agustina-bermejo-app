create table payment_gateway_config_change (
    id bigint generated by default as identity,
    changed_at timestamp(6) not null,
    changed_by_id bigint not null references person,
    mp_enabled_before boolean not null,
    mp_enabled_after boolean not null,
    bank_alias_before varchar(50),
    bank_alias_after varchar(50),
    bank_cbu_before varchar(22),
    bank_cbu_after varchar(22),
    account_holder_before varchar(100),
    account_holder_after varchar(100),
    qr_image_path_before varchar(500),
    qr_image_path_after varchar(500),
    primary key (id)
);

create index idx_payment_gateway_config_change_changed_at on payment_gateway_config_change (changed_at);
