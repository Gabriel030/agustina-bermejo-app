create table commission_closure_reminder (
    id bigint generated by default as identity primary key,
    section_kind varchar(20) not null,
    section_id bigint not null,
    days_after_term_end integer not null check (days_after_term_end >= 1),
    sent_at timestamp(6) not null,
    constraint uq_commission_closure_reminder unique (section_kind, section_id, days_after_term_end)
);
