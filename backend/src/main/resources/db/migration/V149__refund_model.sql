create sequence refund_request_id_seq;

create table refund (
    id bigint generated by default as identity,
    version bigint not null default 0,
    refund_request_id bigint not null,
    payment_id bigint not null,
    student_current_account_id bigint not null,
    currency varchar(3) not null,
    status varchar(20) not null,
    method_type varchar(20) not null,
    amount numeric(12,2) not null,
    amount_currency varchar(3) not null,
    destination_account varchar(50) not null,
    destination_holder varchar(120) not null,
    requested_by_person_id bigint not null,
    authorization_request_id bigint,
    requested_on date not null,
    approved_on date,
    completed_on date,
    completion_reference varchar(120),
    failure_reason varchar(500),
    rejection_reason varchar(500),
    primary key (id),
    constraint fk_refund_payment foreign key (payment_id, student_current_account_id) references payment (id, student_current_account_id),
    constraint fk_refund_account_currency foreign key (student_current_account_id, currency) references student_current_account (id, currency),
    constraint fk_refund_requested_by_person foreign key (requested_by_person_id) references person (id),
    constraint fk_refund_authorization_request foreign key (authorization_request_id) references authorization_request (id),
    constraint uk_refund_id_account unique (id, student_current_account_id),
    constraint ck_refund_status check (status in ('REQUESTED', 'APPROVED', 'COMPLETED', 'FAILED', 'REJECTED')),
    constraint ck_refund_method_type check (method_type in ('CASH', 'BANK_TRANSFER', 'CARD', 'WALLET')),
    constraint ck_refund_amount check (amount > 0 and amount_currency = currency),
    constraint ck_refund_currency check (currency in ('ARS', 'USD')),
    constraint ck_refund_approved_on check ((status in ('APPROVED', 'COMPLETED', 'FAILED')) = (approved_on is not null)),
    constraint ck_refund_completion check (
        (status = 'COMPLETED' and completed_on is not null and completion_reference is not null and length(trim(completion_reference)) > 0)
        or (status <> 'COMPLETED' and completed_on is null and completion_reference is null)),
    constraint ck_refund_failure check ((status = 'FAILED') = (failure_reason is not null)),
    constraint ck_refund_rejection check ((status = 'REJECTED') = (rejection_reason is not null))
);

create index ix_refund_account_status on refund (student_current_account_id, status);
create index ix_refund_payment on refund (payment_id, id);
create index ix_refund_authorization_request on refund (authorization_request_id) where authorization_request_id is not null;
create index ix_refund_request on refund (refund_request_id, id);

create table refund_status_change (
    id bigint generated by default as identity,
    refund_id bigint not null,
    event varchar(60) not null,
    from_status varchar(20),
    to_status varchar(20) not null,
    reason varchar(500),
    actor_person_id bigint,
    actor_process varchar(80),
    occurred_at timestamp(6) not null,
    primary key (id),
    constraint fk_refund_status_change_refund foreign key (refund_id) references refund (id),
    constraint fk_refund_status_change_actor foreign key (actor_person_id) references person (id),
    constraint ck_refund_status_change_actor check (num_nonnulls(actor_person_id, actor_process) = 1)
);

create index ix_refund_status_change_refund on refund_status_change (refund_id, id);

create trigger trg_refund_status_change_append_only before update or delete on refund_status_change
    for each row execute function forbid_append_only_row_change();

alter table current_account_entry add constraint fk_current_account_entry_refund
    foreign key (refund_id, student_current_account_id) references refund (id, student_current_account_id);
