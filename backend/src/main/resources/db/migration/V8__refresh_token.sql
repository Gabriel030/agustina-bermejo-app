-- Spec JWT y login. El refresh token se guarda hasheado (SHA-256), nunca en texto plano:
-- si alguien lee la tabla no puede reusar sesiones activas (mismo principio que password).
create table refresh_token (
    id bigint generated by default as identity,
    person_id bigint not null,
    token_hash varchar(255) not null,
    expires_at timestamp not null,
    revoked boolean not null default false,
    created_at timestamp not null,
    primary key (id),
    constraint uk_refresh_token_hash unique (token_hash),
    constraint fk_refresh_token_person foreign key (person_id) references person on delete cascade
);
