-- Épica 7: solicitud de alta en carrera para el registro independiente. Entidad
-- separada de ProgramEnrollment (no un estado nuevo en ProgramEnrollmentStatus)
-- para mantener el invariante "todo ProgramEnrollment existente está activo o
-- fue baja" — mismo criterio que Prospect es una entidad separada de Student.
create table program_enrollment_application (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    student_id bigint not null references student(id) on delete cascade,
    program_id bigint not null references program(id),
    status varchar(20) not null,
    requested_at timestamp not null,
    decided_by_id bigint references person(id),
    decided_at timestamp,
    rejection_reason varchar(1000)
);

-- Solo una solicitud PENDING a la vez por (student, program) — mismo patrón de
-- índice único parcial que ya usa el proyecto para "solo un X en curso a la vez".
create unique index uk_program_enrollment_application_pending
    on program_enrollment_application (student_id, program_id)
    where status = 'PENDING';

create index ix_program_enrollment_application_status
    on program_enrollment_application (status);
