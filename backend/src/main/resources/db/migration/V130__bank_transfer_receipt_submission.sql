do $$
declare
    orphan_receipts bigint;
begin
    select count(*) into orphan_receipts
    from bank_transfer_receipt r
    where r.payment_id is not null
      and not exists (select 1 from payment p where p.id = r.payment_id);
    if orphan_receipts > 0 then
        raise exception 'V130 aborted: % bank transfer receipt(s) point to a payment id that is not in the payment table; regenerate the database instead of linking legacy receipts', orphan_receipts;
    end if;
end
$$;

alter table bank_transfer_receipt
    add column declared_amount numeric(12,2),
    add column declared_amount_currency varchar(3),
    add column transfer_date date,
    add column operation_number varchar(50),
    add column origin_account varchar(50),
    add column holder_name varchar(120);

alter table bank_transfer_receipt add constraint ck_bank_transfer_receipt_declared_amount
    check ((declared_amount is null and declared_amount_currency is null)
        or (declared_amount > 0 and declared_amount_currency in ('ARS', 'USD')));

alter table bank_transfer_receipt add constraint fk_bank_transfer_receipt_payment
    foreign key (payment_id) references payment (id);

drop index uk_bank_transfer_receipt_pending;

create unique index uk_bank_transfer_receipt_pending on bank_transfer_receipt (invoice_id)
    where status = 'PENDING_REVIEW' and payment_id is null;

create unique index uk_payment_bank_transfer_duplicate on payment ((method_details ->> 'operationNumber'), (method_details ->> 'transferDate'), amount)
    where method_type = 'BANK_TRANSFER' and status not in ('REJECTED', 'CANCELLED');

create table payment_checkout_item (
    id bigint generated by default as identity,
    payment_id bigint not null,
    student_current_account_id bigint not null,
    invoice_id bigint not null,
    position integer not null,
    outstanding_at_selection numeric(12,2) not null,
    outstanding_at_selection_currency varchar(3) not null,
    marked_under_review boolean not null,
    primary key (id),
    constraint fk_payment_checkout_item_payment foreign key (payment_id, student_current_account_id) references payment (id, student_current_account_id),
    constraint fk_payment_checkout_item_invoice foreign key (invoice_id) references invoice (id),
    constraint uk_payment_checkout_item_position unique (payment_id, position),
    constraint uk_payment_checkout_item_invoice unique (payment_id, invoice_id),
    constraint ck_payment_checkout_item_position check (position >= 1),
    constraint ck_payment_checkout_item_outstanding check (outstanding_at_selection > 0 and outstanding_at_selection_currency in ('ARS', 'USD'))
);

create index ix_payment_checkout_item_invoice_id on payment_checkout_item (invoice_id);
