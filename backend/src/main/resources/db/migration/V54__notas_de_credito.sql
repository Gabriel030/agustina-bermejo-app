create table credit_note (
    id bigint generated by default as identity,
    version bigint not null default 0,
    student_id bigint not null,
    amount numeric(12,2) not null,
    reason_type varchar(40) not null,
    reason varchar(500) not null,
    status varchar(20) not null,
    created_by_id bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint fk_credit_note_student foreign key (student_id) references student,
    constraint fk_credit_note_created_by foreign key (created_by_id) references person
);

create table credit_note_source_invoice (
    credit_note_id bigint not null,
    invoice_id bigint not null,
    primary key (credit_note_id, invoice_id),
    constraint fk_cnsi_credit_note foreign key (credit_note_id) references credit_note,
    constraint fk_cnsi_invoice foreign key (invoice_id) references invoice
);

create table credit_application (
    id bigint generated by default as identity,
    credit_note_id bigint not null,
    invoice_id bigint not null,
    payment_id bigint,
    amount_applied numeric(12,2) not null,
    created_at timestamp(6) not null,
    primary key (id),
    constraint fk_ca_credit_note foreign key (credit_note_id) references credit_note,
    constraint fk_ca_invoice foreign key (invoice_id) references invoice,
    constraint fk_ca_payment foreign key (payment_id) references payment
);

create index idx_credit_note_student on credit_note (student_id);
create index idx_credit_application_credit_note on credit_application (credit_note_id);
create index idx_credit_application_invoice on credit_application (invoice_id);
create index idx_credit_application_payment on credit_application (payment_id);
