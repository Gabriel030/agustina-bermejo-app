create table certificate_exception_approval (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    student_id bigint not null references student (id),
    kind varchar(20) not null,
    program_enrollment_id bigint references program_enrollment (id),
    course_enrollment_id bigint references course_enrollment (id),
    organism_kind varchar(30) not null,
    organism_reference varchar(200) not null,
    reason varchar(1000) not null,
    status varchar(20) not null,
    requested_by_id bigint not null references person (id),
    requested_at timestamp not null,
    decided_by_id bigint references person (id),
    decided_at timestamp,
    decision_reason varchar(500),
    valid_until timestamp,
    consumed_at timestamp,
    consumed_certificate_id bigint references regular_student_certificate (id),
    constraint certificate_exception_approval_kind_enum check (kind in ('COURSE', 'PROGRAM')),
    constraint certificate_exception_approval_organism_kind_enum check (organism_kind in ('CONSUMER_DEFENSE', 'COURT', 'EDUCATION_MINISTRY', 'OTHER')),
    constraint certificate_exception_approval_status_enum check (status in ('APPROVED', 'CONSUMED', 'EXPIRED', 'PENDING', 'REJECTED', 'WITHDRAWN')),
    constraint ck_certificate_exception_one_enrollment check ((program_enrollment_id is null) <> (course_enrollment_id is null)),
    constraint ck_certificate_exception_decider_not_requester check (decided_by_id <> requested_by_id),
    constraint ck_certificate_exception_reason_length check (char_length(btrim(reason)) >= 20),
    constraint ck_certificate_exception_reference_present check (char_length(btrim(organism_reference)) >= 1),
    constraint ck_certificate_exception_decision_complete check (status not in ('APPROVED', 'REJECTED', 'CONSUMED', 'EXPIRED')
        or (decided_by_id is not null and decided_at is not null and decision_reason is not null)),
    constraint ck_certificate_exception_approved_has_validity check (status not in ('APPROVED', 'CONSUMED', 'EXPIRED') or valid_until is not null),
    constraint ck_certificate_exception_consumed_complete check (status <> 'CONSUMED' or (consumed_at is not null and consumed_certificate_id is not null))
);

create index ix_certificate_exception_student on certificate_exception_approval (student_id);
create index ix_certificate_exception_status_valid_until on certificate_exception_approval (status, valid_until);
create unique index uq_certificate_exception_consumed_certificate on certificate_exception_approval (consumed_certificate_id)
    where consumed_certificate_id is not null;

create table certificate_exception_status_change (
    id bigint generated by default as identity primary key,
    approval_id bigint not null references certificate_exception_approval (id),
    from_status varchar(20),
    to_status varchar(20) not null,
    event varchar(20) not null,
    actor_person_id bigint references person (id),
    actor_process varchar(80),
    changed_at timestamp not null,
    reason varchar(1000),
    constraint certificate_exception_status_change_from_status_enum check (from_status in ('APPROVED', 'CONSUMED', 'EXPIRED', 'PENDING', 'REJECTED', 'WITHDRAWN')),
    constraint certificate_exception_status_change_to_status_enum check (to_status in ('APPROVED', 'CONSUMED', 'EXPIRED', 'PENDING', 'REJECTED', 'WITHDRAWN')),
    constraint certificate_exception_status_change_event_enum check (event in ('APPROVE', 'CONSUME', 'EXPIRE', 'REJECT', 'REQUEST', 'WITHDRAW')),
    constraint ck_certificate_exception_status_change_actor check ((actor_person_id is null) <> (actor_process is null))
);

create index ix_certificate_exception_status_change_approval on certificate_exception_status_change (approval_id);

alter table regular_student_certificate add constraint fk_regular_cert_exception
    foreign key (exception_id) references certificate_exception_approval (id);
create unique index uq_regular_cert_exception on regular_student_certificate (exception_id) where exception_id is not null;
