alter table payment_allocation rename to legacy_payment_allocation;
alter index payment_allocation_pkey rename to legacy_payment_allocation_pkey;

create table payment_allocation (
    id bigint generated by default as identity primary key,
    student_current_account_id bigint not null,
    invoice_id bigint not null,
    amount numeric(12, 2) not null check (amount > 0),
    amount_currency varchar(3) not null check (amount_currency in ('ARS', 'USD')),
    effective_date date not null,
    allocated_on date not null,
    reverses_allocation_id bigint,
    reason varchar(500),
    actor_person_id bigint references person (id),
    actor_process varchar(80),
    recorded_at timestamp(6) not null,
    constraint uk_payment_allocation_reverses unique (reverses_allocation_id),
    constraint fk_payment_allocation_reverses foreign key (reverses_allocation_id) references payment_allocation (id),
    constraint fk_payment_allocation_invoice_account foreign key (invoice_id, student_current_account_id)
        references invoice (id, student_current_account_id),
    constraint fk_payment_allocation_invoice_currency foreign key (invoice_id, amount_currency)
        references invoice (id, currency),
    constraint ck_payment_allocation_reversal_reason check (reverses_allocation_id is null or (reason is not null and length(trim(reason)) > 0)),
    constraint ck_payment_allocation_actor check (num_nonnulls(actor_person_id, actor_process) = 1)
);

create index ix_payment_allocation_account_newest_first on payment_allocation (student_current_account_id, allocated_on desc, id desc);
create index ix_payment_allocation_by_invoice on payment_allocation (invoice_id);

create function forbid_inconsistent_payment_allocation() returns trigger language plpgsql as $$
begin
    if new.reverses_allocation_id is null then
        if exists (select 1 from payment_allocation a
                   where a.invoice_id = new.invoice_id and a.reverses_allocation_id is null
                     and not exists (select 1 from payment_allocation r where r.reverses_allocation_id = a.id)) then
            raise exception 'invoice % already has a current payment allocation', new.invoice_id using errcode = 'integrity_constraint_violation';
        end if;
    elsif not exists (select 1 from payment_allocation o
                      where o.id = new.reverses_allocation_id and o.reverses_allocation_id is null
                        and o.invoice_id = new.invoice_id and o.amount = new.amount and o.amount_currency = new.amount_currency) then
        raise exception 'a reversal must undo an allocation of the same invoice and amount' using errcode = 'integrity_constraint_violation';
    end if;
    return new;
end;
$$;

create trigger trg_payment_allocation_consistent before insert on payment_allocation
    for each row execute function forbid_inconsistent_payment_allocation();
create trigger trg_payment_allocation_append_only before update or delete on payment_allocation
    for each row execute function forbid_append_only_row_change();
