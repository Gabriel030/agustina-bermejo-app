create table platform_provisioning_log (
    id bigint generated by default as identity primary key,
    actor_person_id bigint not null references person,
    occurred_at timestamp(6) not null,
    reason varchar(500) not null,
    institution_id bigint not null references institution,
    institution_created boolean not null,
    director_person_id bigint not null references person,
    idempotency_key varchar(255),
    request_hash varchar(64) not null,
    constraint uq_platform_provisioning_log_idempotency_key unique (idempotency_key)
);

create index ix_platform_provisioning_log_occurred_at on platform_provisioning_log (occurred_at desc, id desc);
