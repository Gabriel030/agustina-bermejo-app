create table academic_offering_cycle (
    id               bigint generated by default as identity,
    term_id          bigint       not null references term (id),
    program_id       bigint references program (id),
    course_id        bigint references course (id),
    status           varchar(20)  not null default 'DRAFT',
    created_by       bigint       not null references person (id),
    created_at       timestamp    not null,
    decided_by       bigint references person (id),
    decided_at       timestamp,
    rejection_reason varchar(500),
    primary key (id),
    constraint chk_cycle_exactly_one_target
        check (
            (program_id is not null and course_id is null) or
            (program_id is null and course_id is not null)
        )
);

create unique index uk_cycle_program_term_active
    on academic_offering_cycle (program_id, term_id)
    where status in ('DRAFT', 'PENDING_APPROVAL') and program_id is not null;

create unique index uk_cycle_course_term_active
    on academic_offering_cycle (course_id, term_id)
    where status in ('DRAFT', 'PENDING_APPROVAL') and course_id is not null;

alter table subject_section add column academic_offering_cycle_id bigint references academic_offering_cycle (id);
alter table subject_section add column pending_approval boolean not null default false;

alter table course_section add column academic_offering_cycle_id bigint references academic_offering_cycle (id);
alter table course_section add column pending_approval boolean not null default false;
