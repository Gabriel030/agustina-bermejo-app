create table configuration_version (
    id bigint generated by default as identity primary key,
    scope varchar(30) not null check (scope in ('YEAR_TERMS', 'COHORT_ENTRY', 'LATE_PAYMENT', 'ISSUANCE', 'ALLOCATION', 'ANNUAL_UPFRONT', 'COURSE_TERMS', 'IRREGULAR_TERMS')),
    topic_key varchar(120) not null,
    program_id bigint references program (id) on delete cascade,
    term_id bigint references term (id) on delete cascade,
    course_id bigint references course (id) on delete cascade,
    cohort_id bigint references program_cohort (id) on delete cascade,
    config_values jsonb not null,
    status varchar(20) not null check (status in ('PROPOSED', 'SCHEDULED', 'EFFECTIVE', 'SUPERSEDED', 'REJECTED', 'WITHDRAWN', 'EXPIRED', 'CANCELLED')),
    effective_from date not null,
    change_reason varchar(1000) not null check (length(change_reason) > 0),
    authorization_request_id bigint references authorization_request (id),
    previous_version_id bigint references configuration_version (id) on delete set null,
    proposed_by_id bigint not null references person (id),
    proposed_at timestamptz not null,
    decided_by_id bigint references person (id),
    decided_at timestamptz,
    decision_reason varchar(1000),
    direct_publication boolean not null default false,
    cancelled_by_id bigint references person (id),
    cancelled_at timestamptz,
    cancellation_reason varchar(1000),
    version bigint not null default 0,
    constraint ck_configuration_version_decided check (status in ('PROPOSED', 'WITHDRAWN', 'EXPIRED') or (decided_by_id is not null and decided_at is not null)),
    constraint ck_configuration_version_cancel_reason check (status <> 'CANCELLED' or cancellation_reason is not null),
    constraint ck_configuration_version_reject_reason check (status <> 'REJECTED' or decision_reason is not null),
    constraint ck_configuration_version_topic check (
        (scope in ('YEAR_TERMS', 'ANNUAL_UPFRONT') and program_id is not null and term_id is not null and course_id is null and cohort_id is null)
        or (scope = 'COHORT_ENTRY' and cohort_id is not null and program_id is null and term_id is null and course_id is null)
        or (scope = 'COURSE_TERMS' and course_id is not null and program_id is null and term_id is null and cohort_id is null)
        or (scope in ('LATE_PAYMENT', 'ISSUANCE', 'ALLOCATION', 'IRREGULAR_TERMS') and program_id is null and term_id is null and course_id is null and cohort_id is null))
);

create unique index uk_configuration_version_open_topic on configuration_version (scope, topic_key) where status = 'PROPOSED';
create index ix_configuration_version_resolution on configuration_version (scope, topic_key, effective_from desc) where status in ('SCHEDULED', 'EFFECTIVE', 'SUPERSEDED');
create index ix_configuration_version_authorization_request on configuration_version (authorization_request_id);

create table configuration_version_status_change (
    id bigint generated by default as identity primary key,
    configuration_version_id bigint not null references configuration_version (id) on delete cascade,
    from_status varchar(20),
    to_status varchar(20) not null,
    event varchar(30) not null,
    actor_person_id bigint references person (id),
    actor_process varchar(80),
    changed_at timestamptz not null,
    reason varchar(1000),
    check ((actor_person_id is null) <> (actor_process is null))
);

create index ix_configuration_version_status_change_version on configuration_version_status_change (configuration_version_id);

create temporary table migration_default_actor as
select coalesce(
    (select p.id from person p join person_role pr on pr.person_id = p.id join role r on r.id = pr.role_id where r.name = 'DIRECTOR' order by p.id limit 1),
    (select min(id) from person)) as person_id;

