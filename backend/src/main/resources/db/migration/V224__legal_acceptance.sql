create table legal_acceptance (
    id bigint generated by default as identity primary key,
    person_id bigint not null references person,
    document_type varchar(20) not null,
    version varchar(40) not null,
    accepted_at timestamp(6) not null,
    ip_hash varchar(64),
    user_agent_summary varchar(120),
    constraint uq_legal_acceptance_person_type_version unique (person_id, document_type, version)
);

create index ix_legal_acceptance_type_version on legal_acceptance (document_type, version, accepted_at desc);

alter table legal_acceptance
    add constraint legal_acceptance_document_type_enum check (document_type in ('PRIVACY', 'TERMS')) not valid;

alter table legal_acceptance validate constraint legal_acceptance_document_type_enum;
