    id bigint generated by default as identity primary key,
    message_template_id bigint not null references message_template (id),
    provider_template_name varchar(120) not null,
    language_code varchar(10) not null,
    status varchar(20) not null,
    variable_order jsonb not null default '[]'::jsonb,
    updated_by bigint not null,
    updated_at timestamptz not null,
    constraint uq_whatsapp_template_mapping_message_template unique (message_template_id),
    constraint whatsapp_template_mapping_status_enum check (status in ('APPROVED', 'PENDING', 'REJECTED'))
);
