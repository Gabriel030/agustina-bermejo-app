where scope = 'LATE_PAYMENT';

insert into configuration_version_status_change (configuration_version_id, from_status, to_status, event, actor_process, changed_at, reason)
select id, null, status,
       case status when 'PROPOSED' then 'PROPOSE' when 'SCHEDULED' then 'PUBLISH_FOR_FUTURE' else 'PUBLISH_FOR_TODAY' end,
       'LateFeeCapRemovalMigration', now(),
       'D-239: el recargo no tiene tope; el cobro queda deshabilitado hasta que el director revise la mora (D-210)'
from configuration_version
where scope = 'LATE_PAYMENT';

create table late_fee_charge (
    id bigint generated by default as identity primary key,
    debit_note_id bigint not null,
    origin_invoice_id bigint not null,
    student_current_account_id bigint not null,
    month_ordinal integer not null check (month_ordinal >= 1),
    fact_date date not null,
    late_payment_version_id bigint not null references configuration_version (id),
    monthly_rate numeric(8, 6) not null check (monthly_rate >= 0 and monthly_rate <= 1),
    base_amount numeric(12, 2) not null check (base_amount >= 0),
    currency varchar(3) not null check (currency in ('ARS', 'USD')),
    created_at timestamp(6) not null,
    constraint uk_late_fee_charge_debit_note unique (debit_note_id),
    constraint uk_late_fee_charge_origin_month unique (origin_invoice_id, month_ordinal),
    constraint ck_late_fee_charge_debit_note_not_origin check (debit_note_id <> origin_invoice_id),
    constraint fk_late_fee_charge_debit_note foreign key (debit_note_id, student_current_account_id)
        references invoice (id, student_current_account_id),
    constraint fk_late_fee_charge_origin foreign key (origin_invoice_id, student_current_account_id)
        references invoice (id, student_current_account_id)
);

create index ix_late_fee_charge_account on late_fee_charge (student_current_account_id);
