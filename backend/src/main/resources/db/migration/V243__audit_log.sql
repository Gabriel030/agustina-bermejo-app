create table audit_log (
    id bigint generated by default as identity primary key,
    occurred_at timestamp(6) not null,
    actor_person_id bigint references person (id),
    actor_role varchar(30),
    action varchar(40) not null,
    entity_type varchar(40) not null,
    entity_id bigint not null,
    before_value varchar(100),
    after_value varchar(100),
    reason varchar(500),
    constraint ck_audit_log_action check (action in ('STAFF_WITHDRAWN', 'STAFF_REACTIVATED')),
    constraint ck_audit_log_entity_type check (entity_type in ('PERSON'))
);

create index ix_audit_log_occurred_at on audit_log (occurred_at desc, id desc);
create index ix_audit_log_entity on audit_log (entity_type, entity_id, occurred_at desc);
