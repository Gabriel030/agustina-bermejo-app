alter table payment rename to legacy_payment;
alter index payment_pkey rename to legacy_payment_pkey;
alter index uk_payment_external_reference rename to uk_legacy_payment_external_reference;
alter sequence payment_id_seq rename to legacy_payment_id_seq;

create table payment (
    id bigint generated by default as identity,
    version bigint not null default 0,
    student_current_account_id bigint not null,
    currency varchar(3) not null,
    status varchar(20) not null,
    gateway varchar(20) not null,
    method_type varchar(20) not null,
    amount numeric(12,2) not null,
    amount_currency varchar(3) not null,
    approved_amount numeric(12,2),
    approved_amount_currency varchar(3),
    refunded_amount numeric(12,2) not null default 0,
    refunded_amount_currency varchar(3) not null,
    gateway_payment_id varchar(120),
    gateway_raw_status varchar(120),
    gateway_raw_status_detail varchar(255),
    paid_on date,
    registered_at timestamp(6) not null,
    started_at timestamp(6) not null,
    method_details jsonb not null,
    dispute_opened_at timestamp(6),
    dispute_closed_at timestamp(6),
    registered_by_person_id bigint,
    registered_by_process varchar(80),
    reviewed_by_person_id bigint,
    review_note varchar(500),
    rejection_reason varchar(500),
    idempotency_key varchar(100),
    primary key (id),
    constraint fk_payment_account_currency foreign key (student_current_account_id, currency)
        references student_current_account (id, currency),
    constraint uk_payment_id_account unique (id, student_current_account_id),
    constraint uk_payment_idempotency_key unique (idempotency_key),
    constraint fk_payment_registered_by_person foreign key (registered_by_person_id) references person (id),
    constraint fk_payment_reviewed_by_person foreign key (reviewed_by_person_id) references person (id),
    constraint ck_payment_status check (status in ('PENDING', 'AUTHORIZED', 'APPROVED', 'REJECTED', 'REFUNDED', 'CHARGED_BACK', 'CANCELLED')),
    constraint ck_payment_gateway check (gateway in ('MANUAL', 'MERCADO_PAGO', 'DLOCAL')),
    constraint ck_payment_method_type check (method_type in ('CASH', 'BANK_TRANSFER', 'CARD', 'WALLET')),
    constraint ck_payment_currency check (currency in ('ARS', 'USD')),
    constraint ck_payment_amount_positive check (amount > 0),
    constraint ck_payment_amount_currency check (amount_currency = currency),
    constraint ck_payment_approved_amount check (approved_amount is null or (approved_amount > 0 and approved_amount_currency = currency)),
    constraint ck_payment_refunded_amount check (refunded_amount >= 0 and refunded_amount_currency = currency and refunded_amount <= coalesce(approved_amount, amount)),
    constraint ck_payment_paid_on_when_money_received check (status not in ('APPROVED', 'REFUNDED', 'CHARGED_BACK') or (paid_on is not null and approved_amount is not null)),
    constraint ck_payment_registered_by check (num_nonnulls(registered_by_person_id, registered_by_process) = 1)
);

create unique index uk_payment_gateway_payment_id on payment (gateway, gateway_payment_id) where gateway_payment_id is not null;
create index ix_payment_account_registered_at on payment (student_current_account_id, registered_at desc, id desc);
create index ix_payment_status on payment (status);

create table payment_status_change (
    id bigint generated by default as identity,
    payment_id bigint not null,
    event varchar(60) not null,
    from_status varchar(20),
    to_status varchar(20) not null,
    reason varchar(500),
    gateway_raw_status varchar(120),
    gateway_raw_status_detail varchar(255),
    actor_person_id bigint,
    actor_process varchar(80),
    occurred_at timestamp(6) not null,
    primary key (id),
    constraint fk_payment_status_change_payment foreign key (payment_id) references payment (id),
    constraint fk_payment_status_change_actor foreign key (actor_person_id) references person (id),
    constraint ck_payment_status_change_actor check (num_nonnulls(actor_person_id, actor_process) = 1)
);

create index ix_payment_status_change_payment on payment_status_change (payment_id, id);

create trigger trg_payment_status_change_append_only before update or delete on payment_status_change
    for each row execute function forbid_append_only_row_change();

create table idempotency_record (
    idempotency_key varchar(100) not null,
    operation_type varchar(60) not null,
    request_hash varchar(64) not null,
    response_status integer,
    response_body jsonb,
    created_at timestamp(6) not null,
    primary key (idempotency_key),
    constraint ck_idempotency_record_response check ((response_status is null) = (response_body is null))
);

create index ix_idempotency_record_created_at on idempotency_record (created_at);
