create table invoice_line (
    id bigint generated by default as identity primary key,
    invoice_id bigint not null,
    currency varchar(3) not null,
    line_number integer not null check (line_number >= 1),
    fee_type varchar(30) not null check (fee_type in ('MONTHLY_INSTALLMENT', 'ENROLLMENT_FEE', 'EXAM_FEE',
        'RETAKEN_SUBJECT_FEE', 'DEGREE_ISSUANCE_FEE', 'ADMINISTRATIVE_FEE', 'LATE_FEE')),
    concept varchar(200) not null,
    period date not null,
    program_enrollment_id bigint references program_enrollment,
    course_enrollment_id bigint references course_enrollment,
    subject_id bigint references subject,
    exam_board_registration_id bigint references exam_board_registration,
    price_revision_id bigint references price_revision,
    charge_key varchar(120) not null check (length(charge_key) > 0),
    charge_key_released_at timestamp(6),
    amount numeric(12, 2) not null check (amount > 0),
    amount_currency varchar(3) not null,
    discount_amount numeric(12, 2) not null check (discount_amount >= 0),
    discount_amount_currency varchar(3) not null,
    credited_amount numeric(12, 2) not null check (credited_amount >= 0),
    credited_amount_currency varchar(3) not null,
    constraint fk_invoice_line_invoice foreign key (invoice_id, currency) references invoice (id, currency),
    constraint uk_invoice_line_number unique (invoice_id, line_number),
    constraint ck_invoice_line_currencies check (amount_currency = currency and discount_amount_currency = currency
        and credited_amount_currency = currency),
    constraint ck_invoice_line_discount_within_amount check (discount_amount <= amount),
    constraint ck_invoice_line_credited_within_net check (credited_amount <= amount - discount_amount),
    constraint ck_invoice_line_single_enrollment check (num_nonnulls(program_enrollment_id, course_enrollment_id) <= 1),
    constraint ck_invoice_line_priced_fees_have_price_revision check (fee_type not in ('MONTHLY_INSTALLMENT', 'ENROLLMENT_FEE')
        or price_revision_id is not null)
);

create unique index uk_invoice_line_charge_key on invoice_line (charge_key) where charge_key_released_at is null;
create index ix_invoice_line_program_enrollment on invoice_line (program_enrollment_id) where program_enrollment_id is not null;
create index ix_invoice_line_course_enrollment on invoice_line (course_enrollment_id) where course_enrollment_id is not null;

create table invoice_discount (
    id bigint generated by default as identity primary key,
    invoice_line_id bigint not null references invoice_line,
    student_discount_id bigint,
    discount_type varchar(20) not null check (discount_type in ('SCHOLARSHIP', 'PROMOTION', 'ANNUAL_UPFRONT', 'COHORT_ENTRY', 'MANUAL')),
    concept varchar(200) not null,
    currency varchar(3) not null check (currency in ('ARS', 'USD')),
    base_amount numeric(12, 2) not null,
    base_amount_currency varchar(3) not null,
    discount_amount numeric(12, 2) not null,
    discount_amount_currency varchar(3) not null,
    installment_number integer,
    installments_total integer,
    constraint uk_invoice_discount_line unique (invoice_line_id),
    constraint ck_invoice_discount_currencies check (base_amount_currency = currency and discount_amount_currency = currency),
    constraint ck_invoice_discount_positive_within_base check (discount_amount > 0 and discount_amount <= base_amount),
    constraint ck_invoice_discount_installments check ((installment_number is null and installments_total is null)
        or (installment_number is not null and installment_number >= 1 and (installments_total is null or installment_number <= installments_total)))
);

create table invoice_status_change (
    id bigint generated by default as identity primary key,
    invoice_id bigint not null references invoice,
    status_kind varchar(10) not null check (status_kind in ('DOCUMENT', 'PAYMENT')),
    from_status varchar(25),
    to_status varchar(25) not null,
    event varchar(60) not null,
    reason varchar(500),
    actor_person_id bigint references person,
    actor_process varchar(80),
    business_date date,
    occurred_at timestamp(6) not null,
    constraint ck_invoice_status_change_one_actor check (num_nonnulls(actor_person_id, actor_process) = 1),
    constraint ck_invoice_status_change_values check (
        (status_kind = 'DOCUMENT' and to_status in ('DRAFT', 'AWAITING_PAYMENT', 'ISSUED', 'DISCARDED')
            and (from_status is null or from_status in ('DRAFT', 'AWAITING_PAYMENT', 'ISSUED', 'DISCARDED')))
        or (status_kind = 'PAYMENT' and to_status in ('PENDING', 'PAYMENT_UNDER_REVIEW', 'PAID', 'OVERDUE', 'CANCELLED')
            and (from_status is null or from_status in ('PENDING', 'PAYMENT_UNDER_REVIEW', 'PAID', 'OVERDUE', 'CANCELLED'))))
);

create index ix_invoice_status_change_invoice on invoice_status_change (invoice_id, occurred_at);

create table current_account_entry (
    id bigint generated by default as identity primary key,
    student_current_account_id bigint not null,
    currency varchar(3) not null,
    sequence_number bigint not null check (sequence_number >= 1),
    direction varchar(6) not null check (direction in ('DEBIT', 'CREDIT')),
    entry_type varchar(25) not null check (entry_type in ('INVOICE_ISSUED', 'DEBIT_NOTE_ISSUED', 'PAYMENT_RECEIVED',
        'CREDIT_NOTE_ISSUED', 'PAYMENT_REVERSED', 'REFUND_PAID')),
    amount numeric(12, 2) not null check (amount > 0),
    amount_currency varchar(3) not null,
    running_balance_amount numeric(12, 2) not null check (running_balance_amount >= 0),
    running_balance_amount_currency varchar(3) not null,
    running_balance_side varchar(10) not null check (running_balance_side in ('OWES', 'ZERO', 'IN_FAVOR')),
    effective_date date not null,
    recorded_at timestamp(6) not null,
    concept varchar(200) not null,
    invoice_id bigint,
    payment_id bigint,
    credit_note_id bigint,
    refund_id bigint,
    compensates_entry_id bigint,
    constraint fk_current_account_entry_account foreign key (student_current_account_id, currency)
        references student_current_account (id, currency),
    constraint fk_current_account_entry_invoice foreign key (invoice_id, student_current_account_id)
        references invoice (id, student_current_account_id),
    constraint uk_current_account_entry_id_account unique (id, student_current_account_id),
    constraint uk_current_account_entry_sequence unique (student_current_account_id, sequence_number),
    constraint uk_current_account_entry_compensates unique (compensates_entry_id),
    constraint ck_current_account_entry_currencies check (amount_currency = currency and running_balance_amount_currency = currency),
    constraint ck_current_account_entry_zero_side check ((running_balance_side = 'ZERO') = (running_balance_amount = 0)),
    constraint ck_current_account_entry_direction_by_type check (
        (entry_type in ('INVOICE_ISSUED', 'DEBIT_NOTE_ISSUED', 'PAYMENT_REVERSED', 'REFUND_PAID') and direction = 'DEBIT')
        or (entry_type in ('PAYMENT_RECEIVED', 'CREDIT_NOTE_ISSUED') and direction = 'CREDIT')),
    constraint ck_current_account_entry_source_by_type check (
        (entry_type in ('INVOICE_ISSUED', 'DEBIT_NOTE_ISSUED') and invoice_id is not null
            and num_nonnulls(payment_id, credit_note_id, refund_id, compensates_entry_id) = 0)
        or (entry_type = 'PAYMENT_RECEIVED' and payment_id is not null
            and num_nonnulls(invoice_id, credit_note_id, refund_id, compensates_entry_id) = 0)
        or (entry_type = 'PAYMENT_REVERSED' and payment_id is not null and compensates_entry_id is not null
            and num_nonnulls(invoice_id, credit_note_id, refund_id) = 0)
        or (entry_type = 'CREDIT_NOTE_ISSUED' and credit_note_id is not null
            and num_nonnulls(invoice_id, payment_id, refund_id, compensates_entry_id) = 0)
        or (entry_type = 'REFUND_PAID' and refund_id is not null
            and num_nonnulls(invoice_id, payment_id, credit_note_id, compensates_entry_id) = 0))
);

