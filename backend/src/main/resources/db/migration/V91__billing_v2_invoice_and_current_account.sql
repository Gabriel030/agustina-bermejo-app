create table invoice (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    student_current_account_id bigint not null,
    currency varchar(3) not null check (currency in ('ARS', 'USD')),
    document_type varchar(20) not null check (document_type in ('INVOICE', 'DEBIT_NOTE')),
    invoice_type varchar(30) not null check (invoice_type in ('MONTHLY_INSTALLMENT', 'ANNUAL_UPFRONT', 'ENROLLMENT_FEE',
        'EXAM_FEE', 'RETAKEN_SUBJECT_FEE', 'DEGREE_ISSUANCE_FEE', 'ADMINISTRATIVE_FEE', 'LATE_FEE')),
    issuing_reason varchar(40) not null check (issuing_reason in ('MONTHLY_JOB', 'CATCH_UP', 'PLAN_SELECTION', 'REACTIVATION',
        'ENROLLMENT_FEE_ON_DEMAND', 'CONFIGURATION_CHANGE', 'ANNUAL_UPFRONT_PAYMENT', 'ADMISSION', 'COURSE_MONTHLY',
        'COURSE_ADMISSION', 'AD_HOC', 'LATE_FEE')),
    document_status varchar(20) not null check (document_status in ('DRAFT', 'AWAITING_PAYMENT', 'ISSUED', 'DISCARDED')),
    payment_status varchar(25) check (payment_status in ('PENDING', 'PAYMENT_UNDER_REVIEW', 'PAID', 'OVERDUE', 'CANCELLED')),
    invoice_number varchar(20),
    issue_date date,
    due_date date,
    payment_deadline timestamp(6),
    origin_invoice_id bigint,
    student_snapshot jsonb,
    discarded_reason varchar(500),
    lines_total numeric(12, 2) not null check (lines_total >= 0),
    lines_total_currency varchar(3) not null,
    discounts_total numeric(12, 2) not null check (discounts_total >= 0),
    discounts_total_currency varchar(3) not null,
    total numeric(12, 2) not null check (total >= 0),
    total_currency varchar(3) not null,
    paid_amount numeric(12, 2) not null check (paid_amount >= 0),
    paid_amount_currency varchar(3) not null,
    credited_amount numeric(12, 2) not null check (credited_amount >= 0),
    credited_amount_currency varchar(3) not null,
    outstanding_amount numeric(12, 2) not null check (outstanding_amount >= 0),
    outstanding_amount_currency varchar(3) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_invoice_student_current_account foreign key (student_current_account_id, currency)
        references student_current_account (id, currency),
    constraint uk_invoice_id_account unique (id, student_current_account_id),
    constraint uk_invoice_id_currency unique (id, currency),
    constraint uk_invoice_number unique (invoice_number),
    constraint ck_invoice_amount_currencies check (lines_total_currency = currency and discounts_total_currency = currency
        and total_currency = currency and paid_amount_currency = currency and credited_amount_currency = currency
        and outstanding_amount_currency = currency),
    constraint ck_invoice_total_formula check (total = lines_total - discounts_total),
    constraint ck_invoice_outstanding_formula check (outstanding_amount = total - paid_amount - credited_amount),
    constraint ck_invoice_no_partial_payment check (paid_amount = 0 or outstanding_amount = 0),
    constraint ck_invoice_payment_status_only_when_issued check ((document_status = 'ISSUED') = (payment_status is not null)),
    constraint ck_invoice_issued_fields_present check (document_status <> 'ISSUED'
        or (invoice_number is not null and issue_date is not null and due_date is not null and student_snapshot is not null)),
    constraint ck_invoice_issued_fields_absent check (document_status = 'ISSUED'
        or num_nonnulls(invoice_number, issue_date, due_date, student_snapshot) = 0),
    constraint ck_invoice_due_date_not_before_issue_date check (due_date >= issue_date),
    constraint ck_invoice_payment_deadline_only_annual check (payment_deadline is null or invoice_type = 'ANNUAL_UPFRONT'),
    constraint ck_invoice_awaiting_payment_has_deadline check (document_status <> 'AWAITING_PAYMENT' or payment_deadline is not null),
    constraint ck_invoice_no_money_before_issue check (document_status = 'ISSUED' or (paid_amount = 0 and credited_amount = 0)),
    constraint ck_invoice_open_status_amounts check (payment_status not in ('PENDING', 'PAYMENT_UNDER_REVIEW', 'OVERDUE')
        or (paid_amount = 0 and outstanding_amount > 0)),
    constraint ck_invoice_paid_status_amounts check (payment_status <> 'PAID' or outstanding_amount = 0),
    constraint ck_invoice_cancelled_status_amounts check (payment_status <> 'CANCELLED'
        or (paid_amount = 0 and outstanding_amount = 0 and credited_amount = total)),
    constraint ck_invoice_zero_total_is_paid check (total > 0 or payment_status is null or payment_status = 'PAID'),
    constraint ck_invoice_debit_note_is_late_fee check ((document_type = 'DEBIT_NOTE') = (invoice_type = 'LATE_FEE')),
    constraint ck_invoice_debit_note_has_origin check ((document_type = 'DEBIT_NOTE') = (origin_invoice_id is not null)),
    constraint ck_invoice_origin_not_itself check (origin_invoice_id <> id),
    constraint ck_invoice_discarded_reason check ((document_status = 'DISCARDED') = (discarded_reason is not null))
);

