create function forbid_append_only_row_change() returns trigger language plpgsql as $$
begin
    raise exception 'append-only table %: % is not allowed', tg_table_name, tg_op using errcode = 'integrity_constraint_violation';
end;
$$;

create trigger trg_current_account_entry_append_only before update or delete on current_account_entry
    for each row execute function forbid_append_only_row_change();
create trigger trg_invoice_status_change_append_only before update or delete on invoice_status_change
    for each row execute function forbid_append_only_row_change();
