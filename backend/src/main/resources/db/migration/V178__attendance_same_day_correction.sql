create table attendance_correction (
    id bigint generated by default as identity, version bigint not null default 0,
    attendance_id bigint not null, corrected_by_id bigint not null,
    previous_status varchar(30) not null, corrected_status varchar(30) not null,
    corrected_at timestamp(6) not null,
    primary key (id),
    constraint fk_attendance_correction_attendance foreign key (attendance_id) references attendance,
    constraint fk_attendance_correction_corrected_by foreign key (corrected_by_id) references instructor
);
create index ix_attendance_correction_attendance on attendance_correction (attendance_id);
