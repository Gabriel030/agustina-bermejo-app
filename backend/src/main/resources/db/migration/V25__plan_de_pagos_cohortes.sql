-- Épica 8 Fase 2: plan de pagos, cohortes y motor de facturación recurrente.
-- Ver spec técnica en Obsidian (Roadmap frontend/Épica 8.../Fase 2 - Plan de
-- pagos, cohortes y motor de facturación recurrente) para el diseño completo.

-- La cohorte es puramente administrativa/de facturación (no se integra con
-- Term/SubjectSection, ver "Contexto verificado" de la spec técnica) — una
-- carrera tiene exactamente 2 cohortes por año (orden_en_anio 1 y 2), cada
-- una con su propia ventana de admisión. orden_en_anio se guarda explícito
-- en vez de inferirse por fecha (auditable, no un cálculo implícito frágil).
create table program_cohort (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    program_id bigint not null references program(id) on delete cascade,
    label varchar(255),
    orden_en_anio integer not null,
    admission_start timestamp,
    admission_end timestamp,
    cursada_start date not null,
    constraint uk_program_cohort_cursada_start unique (program_id, cursada_start)
);

create index ix_program_cohort_program on program_cohort (program_id);

-- Migración de datos: toda carrera con ventana de admisión ya cargada pasa a
-- tener una única cohorte (orden 1) con esos mismos valores — cursada_start
-- se aproxima a la fecha de admission_start a falta de otro dato real. Es una
-- aproximación deliberada sobre datos existentes, no una regla de negocio
-- nueva: no hay forma de inferir el inicio real de cursada de datos viejos
-- que nunca lo registraron.
insert into program_cohort (program_id, label, orden_en_anio, admission_start, admission_end, cursada_start)
select id, 'Cohorte migrada', 1, admission_start, admission_end, admission_start::date
from program
where admission_start is not null;

alter table program drop column admission_start;
alter table program drop column admission_end;
alter table program add column cuotas_por_anio_lectivo integer;

-- Nullable a propósito (mismo criterio que payment_receipt_id en V24): filas
-- viejas de una DB de dev persistente no tienen cohorte asociada. El código
-- nuevo siempre la setea al solicitar/matricular.
alter table program_enrollment_application
    add column program_cohort_id bigint references program_cohort(id);

alter table program_enrollment
    add column program_cohort_id bigint references program_cohort(id);

-- Vínculo de Invoice a la matriculación real, con su número de cuota dentro
-- del plan de pagos — sin esto no hay forma de saber programáticamente "esta
-- factura es la cuota 4 de 10 de tal matriculación" (gap que esta fase
-- cierra, ver Contexto verificado de la spec técnica). Ambos FK nullable y
-- mutuamente excluyentes cuando están seteados: null/null para facturación
-- ad-hoc (InvoiceService.crear, sin cambios), exactamente uno de los dos
-- para matrícula/cuota generada desde un plan de pagos.
alter table invoice add column program_enrollment_id bigint references program_enrollment(id);
alter table invoice add column course_enrollment_id bigint references course_enrollment(id);
alter table invoice add column installment_number integer;
alter table invoice add column total_installments integer;

alter table invoice add constraint chk_invoice_enrollment_target
    check (program_enrollment_id is null or course_enrollment_id is null);

-- Idempotencia del motor de facturación recurrente (decisión técnica clave,
-- ver spec): un reintento tras una falla a mitad de camino, o correr el
-- motor manualmente además del cron, nunca duplica la cuota N de una misma
-- matriculación. Dos índices únicos parciales (uno por tipo de matriculación,
-- ya que installment_number es null para matrícula/facturación ad-hoc).
create unique index uk_invoice_program_enrollment_installment
    on invoice (program_enrollment_id, installment_number)
    where program_enrollment_id is not null and installment_number is not null;

create unique index uk_invoice_course_enrollment_installment
    on invoice (course_enrollment_id, installment_number)
    where course_enrollment_id is not null and installment_number is not null;
