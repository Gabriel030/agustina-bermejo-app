select id, null, case when status = 'SCHEDULED' then 'SCHEDULED' else 'EFFECTIVE' end,
       case when status = 'SCHEDULED' then 'PUBLISH_FOR_FUTURE' else 'PUBLISH_FOR_TODAY' end,
       'LegacyPriceRevisionMigration', proposed_at, change_reason
from price_version;

