update price_version v
set price_id = p.id
from price p
where p.fee_type = v.fee_type
  and p.program_id is not distinct from v.program_id
  and p.course_id is not distinct from v.course_id;

update price_version v
set status = case
        when v.effective_from > current_date then 'SCHEDULED'
        when v.id = (select r.id from price_version r where r.price_id = v.price_id and r.effective_from <= current_date
                     order by r.effective_from desc, r.created_at desc, r.id desc limit 1) then 'EFFECTIVE'
        else 'SUPERSEDED' end,
    initial_version = (v.id = (select r.id from price_version r where r.price_id = v.price_id
                               order by r.effective_from asc, r.created_at asc, r.id asc limit 1)),
    change_reason = 'Versión migrada de price_revision',
    proposed_by_id = v.created_by_id,
    proposed_at = v.created_at::timestamptz,
    decided_by_id = v.created_by_id,
    decided_at = v.created_at::timestamptz,
    direct_publication = true;

