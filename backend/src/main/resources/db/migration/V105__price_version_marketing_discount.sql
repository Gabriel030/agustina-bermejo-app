do $$
begin
    if exists (select 1 from price_revision r
               left join program p on p.id = r.program_id
               left join course c on c.id = r.course_id
               where r.monthly_amount_currency <> coalesce(p.currency, c.currency)) then
        raise exception 'price_revision rows with a currency different from the currency of their offering cannot be migrated to price_version';
    end if;
end
$$;

create table price (
    id bigint generated by default as identity primary key,
    program_id bigint references program (id),
    course_id bigint references course (id),
    fee_type varchar(30) not null check (fee_type in ('MONTHLY_INSTALLMENT', 'ENROLLMENT_FEE', 'EXAM_FEE',
        'RETAKEN_SUBJECT_FEE', 'DEGREE_ISSUANCE_FEE', 'ADMINISTRATIVE_FEE', 'LATE_FEE')),
    currency varchar(3) not null check (currency in ('ARS', 'USD')),
    description varchar(200) not null,
    version bigint not null default 0,
    constraint ck_price_single_offering check (num_nonnulls(program_id, course_id) = 1)
);

create unique index uk_price_program_fee on price (program_id, fee_type) where program_id is not null;
create unique index uk_price_course_fee on price (course_id, fee_type) where course_id is not null;

insert into price (program_id, course_id, fee_type, currency, description)
select distinct on (program_id, course_id, fee_type) program_id, course_id, fee_type, monthly_amount_currency, description
from price_revision
order by program_id, course_id, fee_type, effective_from desc, created_at desc, id desc;

