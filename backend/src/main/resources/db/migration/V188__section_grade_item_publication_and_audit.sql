create table section_grade_item_publication (
    id bigint generated by default as identity primary key,
    section_kind varchar(20) not null,
    section_id bigint not null,
    grade_item_type varchar(30) not null,
    sequence_number integer not null,
    published_at timestamp(6) not null,
    published_by_id bigint references person (id),
    constraint uq_section_grade_item_publication
        unique (section_kind, section_id, grade_item_type, sequence_number)
);

create table grade_item_audit (
    id bigint generated by default as identity primary key,
    grade_item_id bigint,
    section_kind varchar(20) not null,
    section_id bigint not null,
    enrollment_id bigint not null,
    grade_item_type varchar(30) not null,
    sequence_number integer not null,
    previous_score numeric(4,2),
    new_score numeric(4,2),
    reason varchar(255) not null,
    changed_by_id bigint not null references person (id),
    changed_at timestamp(6) not null,
    kind varchar(20) not null
);

create index ix_grade_item_audit_item on grade_item_audit (grade_item_id);
create index ix_grade_item_audit_section on grade_item_audit (section_kind, section_id);

insert into section_grade_item_publication (section_kind, section_id, grade_item_type, sequence_number, published_at)
select 'PROGRAM', e.program_section_id, g.type, coalesce(g.sequence_number, -1), coalesce(min(g.date), now())
from grade_item g
join subject_section_enrollment e on e.id = g.program_section_enrollment_id
where g.type <> 'FINAL'
group by e.program_section_id, g.type, coalesce(g.sequence_number, -1);

insert into section_grade_item_publication (section_kind, section_id, grade_item_type, sequence_number, published_at)
select 'COURSE', e.course_section_id, g.type, coalesce(g.sequence_number, -1), coalesce(min(g.date), now())
from grade_item g
join course_section_enrollment e on e.id = g.course_section_enrollment_id
where g.type <> 'FINAL'
group by e.course_section_id, g.type, coalesce(g.sequence_number, -1);
