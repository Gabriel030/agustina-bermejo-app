-- Fase 1 (spec funcional): Role real reemplazando Person.rol_id, Long suelto sin FK.
-- Cardinalidad muchos-a-muchos: una persona puede tener más de un rol a la vez
-- (ej. alumno y docente simultáneamente), decisión explícita del usuario que
-- difiere de la nota "rol fijo por usuario" del documento original.

create table role (
    id bigint generated by default as identity,
    name varchar(50) not null,
    description varchar(255),
    primary key (id),
    constraint uk_role_name unique (name)
);

insert into role (name, description) values
    ('ALUMNO', 'Persona cursando una carrera o curso. Autoservicio, alcance limitado a sus propios datos.'),
    ('DOCENTE', 'Dicta materias/comisiones. Alcance limitado a sus comisiones asignadas.'),
    ('PRECEPTOR', 'Gestión operativa del día a día académico. Alcance amplio, sin configuración institucional.'),
    ('ADMINISTRATIVO', 'Secretaría académica: gestión de oferta académica, pagos y usuarios.'),
    ('DIRECTOR', 'Autoridad máxima de la institución: supervisión, aprobación y reportes globales.');

create table person_role (
    person_id bigint not null,
    role_id bigint not null,
    primary key (person_id, role_id),
    constraint fk_person_role_person foreign key (person_id) references person on delete cascade,
    constraint fk_person_role_role foreign key (role_id) references role on delete restrict
);

alter table person drop column rol_id;
