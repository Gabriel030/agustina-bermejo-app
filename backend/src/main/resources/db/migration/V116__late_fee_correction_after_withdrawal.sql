create table late_fee_charge_correction (
    id bigint generated by default as identity primary key,
    late_fee_charge_id bigint not null references late_fee_charge (id),
    debit_note_id bigint not null,
    student_current_account_id bigint not null,
    credit_note_id bigint not null,
    first_corrected_day date not null,
    last_corrected_day date not null,
    corrected_days integer not null,
    cause varchar(30) not null,
    enrollment_end_date date not null,
    created_at timestamp(6) not null,
    constraint uk_late_fee_charge_correction_credit_note unique (credit_note_id),
    constraint fk_late_fee_charge_correction_debit_note foreign key (debit_note_id, student_current_account_id)
        references invoice (id, student_current_account_id),
    constraint fk_late_fee_charge_correction_credit_note foreign key (credit_note_id, student_current_account_id)
        references credit_note (id, student_current_account_id),
    constraint ck_late_fee_charge_correction_day_order check (last_corrected_day >= first_corrected_day),
    constraint ck_late_fee_charge_correction_one_month check (date_trunc('month', first_corrected_day) = date_trunc('month', last_corrected_day)),
    constraint ck_late_fee_charge_correction_days check (corrected_days between 1 and (last_corrected_day - first_corrected_day + 1)),
    constraint ck_late_fee_charge_correction_after_end check (first_corrected_day > enrollment_end_date),
    constraint ck_late_fee_charge_correction_cause check (cause in ('BACKDATED_WITHDRAWAL')),
    constraint ex_late_fee_charge_correction_no_overlapping_days exclude using gist
        (late_fee_charge_id with =, daterange(first_corrected_day, last_corrected_day, '[]') with &&)
);

create index ix_late_fee_charge_correction_charge on late_fee_charge_correction (late_fee_charge_id);
create index ix_late_fee_charge_correction_debit_note on late_fee_charge_correction (debit_note_id, student_current_account_id);

