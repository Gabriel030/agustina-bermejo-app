create table permission (
    id bigint generated by default as identity primary key,
    code varchar(100) not null,
    module varchar(50) not null,
    description varchar(255) not null,
    fixed_to_director boolean not null default false,
    constraint uk_permission_code unique (code),
    constraint ck_permission_code_starts_with_module check (code like module || '.%')
);

create table role_permission (
    id bigint generated by default as identity primary key,
    role varchar(50) not null,
    permission_id bigint not null references permission (id),
    constraint uk_role_permission unique (role, permission_id)
);

create table permission_module_mode (
    id bigint generated by default as identity primary key,
    role varchar(50) not null,
    module varchar(50) not null,
    mode varchar(10) not null default 'LEGACY',
    constraint uk_permission_module_mode unique (role, module),
    constraint permission_module_mode_mode_enum check (mode in ('LEGACY', 'SHADOW', 'ENFORCE'))
);

create table permission_discrepancy_counter (
    id bigint generated by default as identity primary key,
    role varchar(50) not null,
    module varchar(50) not null,
    permission_id bigint not null references permission (id),
    occurrences bigint not null default 0,
    last_seen_at timestamp with time zone not null,
    constraint uk_permission_discrepancy_counter unique (role, permission_id),
    constraint ck_permission_discrepancy_counter_occurrences check (occurrences >= 0)
);

