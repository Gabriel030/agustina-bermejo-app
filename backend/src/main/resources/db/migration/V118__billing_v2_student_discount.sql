create table student_discount (
    id bigint generated by default as identity primary key,
    program_enrollment_id bigint references program_enrollment (id),
    course_enrollment_id bigint references course_enrollment (id),
    student_id bigint not null references student (id),
    currency varchar(3) not null check (currency in ('ARS', 'USD')),
    discount_definition_id bigint references discount_definition (id),
    discount_type varchar(20) not null check (discount_type in ('SCHOLARSHIP', 'INDIVIDUAL')),
    applicable_invoice_type varchar(30) not null check (applicable_invoice_type in ('MONTHLY_INSTALLMENT', 'ANNUAL_UPFRONT', 'ENROLLMENT_FEE',
        'EXAM_FEE', 'RETAKEN_SUBJECT_FEE', 'DEGREE_ISSUANCE_FEE', 'ADMINISTRATIVE_FEE')),
    origin varchar(30) not null check (origin in ('DIRECT_GRANT')),
    calculation jsonb not null,
    cap_per_invoice numeric(12, 2) check (cap_per_invoice > 0),
    cap_per_invoice_currency varchar(3) check (cap_per_invoice_currency in ('ARS', 'USD')),
    priority integer not null check (priority >= 1),
    from_period date not null,
    to_period date not null,
    status varchar(10) not null check (status in ('ACTIVE', 'EXHAUSTED', 'REVOKED', 'ENDED')),
    granted_at timestamptz not null,
    granted_by_id bigint not null references person (id),
    reason varchar(500) not null,
    authorization_request_id bigint references authorization_request (id),
    revoked_at timestamptz,
    revoked_by_id bigint references person (id),
    revocation_reason varchar(500),
    revoked_from_period date,
    version bigint not null default 0,
    constraint ck_student_discount_single_enrollment check (num_nonnulls(program_enrollment_id, course_enrollment_id) = 1),
    constraint ck_student_discount_period_range check (to_period >= from_period),
    constraint ck_student_discount_scholarship_monthly check (discount_type <> 'SCHOLARSHIP' or applicable_invoice_type = 'MONTHLY_INSTALLMENT'),
    constraint ck_student_discount_scholarship_has_definition check (discount_type <> 'SCHOLARSHIP' or discount_definition_id is not null),
    constraint ck_student_discount_individual_no_definition check (discount_type <> 'INDIVIDUAL' or discount_definition_id is null),
    constraint ck_student_discount_cap_currency check ((cap_per_invoice is null) = (cap_per_invoice_currency is null)),
    constraint ck_student_discount_revocation check ((status = 'REVOKED') = (revoked_at is not null)
        and (revoked_at is null or (revoked_by_id is not null and revocation_reason is not null and revoked_from_period is not null)))
);

create index ix_student_discount_program_enrollment on student_discount (program_enrollment_id) where program_enrollment_id is not null;
create index ix_student_discount_course_enrollment on student_discount (course_enrollment_id) where course_enrollment_id is not null;
create index ix_student_discount_student on student_discount (student_id);
create index ix_student_discount_definition on student_discount (discount_definition_id) where discount_definition_id is not null;
create index ix_student_discount_authorization_request on student_discount (authorization_request_id) where authorization_request_id is not null;

create table student_discount_status_change (
    id bigint generated by default as identity primary key,
    student_discount_id bigint not null references student_discount (id),
    from_status varchar(10),
    to_status varchar(10) not null,
    event varchar(30) not null,
    actor_person_id bigint references person (id),
    actor_process varchar(80),
    changed_at timestamptz not null,
    reason varchar(1000),
    check ((actor_person_id is null) <> (actor_process is null))
);

create index ix_student_discount_status_change_discount on student_discount_status_change (student_discount_id);

create trigger trg_student_discount_status_change_append_only before update or delete on student_discount_status_change
    for each row execute function forbid_append_only_row_change();

alter table invoice_discount drop constraint invoice_discount_discount_type_check;
alter table invoice_discount disable trigger trg_invoice_discount_immutable_when_issued;
update invoice_discount set discount_type = 'INDIVIDUAL' where discount_type = 'MANUAL';
alter table invoice_discount enable trigger trg_invoice_discount_immutable_when_issued;
alter table invoice_discount add constraint invoice_discount_discount_type_check
    check (discount_type in ('SCHOLARSHIP', 'PROMOTION', 'ANNUAL_UPFRONT', 'COHORT_ENTRY', 'INDIVIDUAL'));
alter table invoice_discount add column calculation jsonb;
alter table invoice_discount add column consumption_released_at timestamp(6);

create or replace function forbid_issued_invoice_discount_change() returns trigger language plpgsql as $$
begin
    if (select i.document_status from invoice_line l join invoice i on i.id = l.invoice_id where l.id = old.invoice_line_id) = 'ISSUED' then
        if tg_op = 'UPDATE' and old.consumption_released_at is null and new.consumption_released_at is not null
            and (to_jsonb(new) - 'consumption_released_at') = (to_jsonb(old) - 'consumption_released_at') then
            return new;
        end if;
        raise exception 'issued invoice discount is immutable: % is not allowed', tg_op using errcode = 'integrity_constraint_violation';
    end if;
    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end;
$$;
