create table chargeback (
    id bigint generated by default as identity,
    version bigint not null default 0,
    payment_id bigint not null,
    student_current_account_id bigint not null,
    amount numeric(12,2) not null,
    amount_currency varchar(3) not null,
    charged_back_on date not null,
    gateway_reference varchar(120),
    reversed_on date,
    registered_at timestamp(6) not null,
    registered_by_person_id bigint,
    registered_by_process varchar(80),
    reversed_by_person_id bigint,
    reversed_by_process varchar(80),
    primary key (id),
    constraint fk_chargeback_payment foreign key (payment_id, student_current_account_id) references payment (id, student_current_account_id),
    constraint fk_chargeback_registered_by foreign key (registered_by_person_id) references person (id),
    constraint fk_chargeback_reversed_by foreign key (reversed_by_person_id) references person (id),
    constraint ck_chargeback_amount check (amount > 0 and amount_currency in ('ARS', 'USD')),
    constraint ck_chargeback_registered_by check (num_nonnulls(registered_by_person_id, registered_by_process) = 1),
    constraint ck_chargeback_reversal check (
        (reversed_on is null and reversed_by_person_id is null and reversed_by_process is null)
        or (reversed_on is not null and reversed_on >= charged_back_on and num_nonnulls(reversed_by_person_id, reversed_by_process) = 1))
);

create unique index uk_chargeback_open_per_payment on chargeback (payment_id) where reversed_on is null;
create index ix_chargeback_payment on chargeback (payment_id, id);

alter table current_account_entry add column credit_round integer not null default 1;

alter table current_account_entry add constraint ck_current_account_entry_credit_round
    check (credit_round >= 1 and (credit_round = 1 or entry_type = 'PAYMENT_RECEIVED'));

drop index uk_current_account_entry_payment_credit;
create unique index uk_current_account_entry_payment_credit on current_account_entry (payment_id, credit_round)
    where entry_type = 'PAYMENT_RECEIVED';

create function assign_credit_round_of_a_payment() returns trigger language plpgsql as $$
declare
    last_round integer;
begin
    if new.entry_type <> 'PAYMENT_RECEIVED' then
        return new;
    end if;
    select coalesce(max(e.credit_round), 0) into last_round
    from current_account_entry e where e.entry_type = 'PAYMENT_RECEIVED' and e.payment_id = new.payment_id;
    if last_round = 0 then
        new.credit_round := 1;
    elsif exists (select 1 from current_account_entry e
                  where e.entry_type = 'PAYMENT_RECEIVED' and e.payment_id = new.payment_id and e.credit_round = last_round
                    and not exists (select 1 from current_account_entry c where c.compensates_entry_id = e.id)) then
        new.credit_round := last_round;
    else
        new.credit_round := last_round + 1;
    end if;
    return new;
end;
$$;

create trigger trg_current_account_entry_assign_credit_round before insert on current_account_entry
    for each row execute function assign_credit_round_of_a_payment();
