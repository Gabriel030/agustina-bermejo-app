create table import_batch (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    status varchar(30) not null,
    institution_id bigint not null references institution,
    created_by_person_id bigint not null references person,
    created_at timestamp(6) not null,
    validated_at timestamp(6),
    committed_at timestamp(6),
    sealed_at timestamp(6),
    sealed_by_person_id bigint references person,
    billing_mode_at_commit varchar(20),
    summary jsonb,
    version bigint not null default 0
);

create unique index uq_import_batch_one_active_per_institution
    on import_batch (institution_id) where status in ('VALIDATING', 'COMMITTING', 'ROLLING_BACK');

create table import_file (
    id bigint generated by default as identity primary key,
    batch_id bigint not null references import_batch,
    entity_type varchar(40) not null,
    original_name varchar(255) not null,
    sha256 varchar(64) not null,
    size_bytes bigint not null,
    row_count integer not null,
    storage_path varchar(500),
    uploaded_at timestamp(6) not null,
    constraint uq_import_file_batch_entity_type unique (batch_id, entity_type)
);

create table import_row (
    id bigint generated by default as identity primary key,
    batch_id bigint not null references import_batch,
    entity_type varchar(40) not null,
    row_number integer not null,
    natural_key varchar(255) not null,
    content_hash varchar(64) not null,
    payload jsonb not null,
    status varchar(20) not null,
    errors jsonb,
    committed_entity_id bigint
);

create index ix_import_row_batch_entity_status on import_row (batch_id, entity_type, status);
create index ix_import_row_batch_entity_natural_key on import_row (batch_id, entity_type, natural_key);

create table import_created_entity (
    id bigint generated by default as identity primary key,
    batch_id bigint not null references import_batch,
    entity_type varchar(40) not null,
    entity_id bigint not null,
    natural_key varchar(255) not null,
    created_at timestamp(6) not null
);

create index ix_import_created_entity_batch on import_created_entity (batch_id, id desc);

create table import_batch_event (
    id bigint generated by default as identity primary key,
    batch_id bigint not null references import_batch,
    type varchar(30) not null,
    actor_person_id bigint references person,
    occurred_at timestamp(6) not null,
    detail jsonb
);

create index ix_import_batch_event_batch on import_batch_event (batch_id, id);

alter table import_batch add constraint import_batch_status_enum
    check (status in ('DRAFT', 'FILES_UPLOADED', 'VALIDATING', 'VALIDATED', 'VALIDATION_FAILED', 'COMMITTING', 'COMMITTED', 'PARTIAL', 'FAILED', 'SEALED', 'ROLLING_BACK', 'ROLLED_BACK')) not valid;
alter table import_batch validate constraint import_batch_status_enum;

alter table import_file add constraint import_file_entity_type_enum check (entity_type in ('PERSONS')) not valid;
alter table import_file validate constraint import_file_entity_type_enum;

alter table import_row add constraint import_row_entity_type_enum check (entity_type in ('PERSONS')) not valid;
alter table import_row validate constraint import_row_entity_type_enum;

alter table import_row add constraint import_row_status_enum
    check (status in ('PENDING', 'VALID', 'ERROR', 'UNCHANGED', 'CONFLICT', 'COMMITTED', 'FAILED')) not valid;
alter table import_row validate constraint import_row_status_enum;

alter table import_created_entity add constraint import_created_entity_entity_type_enum check (entity_type in ('PERSONS')) not valid;
alter table import_created_entity validate constraint import_created_entity_entity_type_enum;

alter table import_batch_event add constraint import_batch_event_type_enum
    check (type in ('CREATED', 'FILE_UPLOADED', 'VALIDATED', 'COMMITTED', 'RETRIED', 'ROLLED_BACK', 'SEALED')) not valid;
alter table import_batch_event validate constraint import_batch_event_type_enum;
