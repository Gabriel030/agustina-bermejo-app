create table post_withdrawal_summary (
    id bigint generated by default as identity primary key,
    student_id bigint not null references student (id),
    program_enrollment_id bigint references program_enrollment (id),
    course_enrollment_id bigint references course_enrollment (id),
    summary_month date not null,
    business_date date not null,
    created_at timestamp(6) not null,
    constraint ck_post_withdrawal_summary_one_enrollment check ((program_enrollment_id is null) <> (course_enrollment_id is null)),
    constraint ck_post_withdrawal_summary_first_of_month check (extract(day from summary_month) = 1)
);

create unique index uq_post_withdrawal_summary_program_month on post_withdrawal_summary (program_enrollment_id, summary_month) where program_enrollment_id is not null;
create unique index uq_post_withdrawal_summary_course_month on post_withdrawal_summary (course_enrollment_id, summary_month) where course_enrollment_id is not null;
create index ix_post_withdrawal_summary_student on post_withdrawal_summary (student_id);
