-- Épica 7 Fase 3: gating de acceso hasta que se aprueba el pago, tanto para
-- carrera (matrícula) como para curso (primera cuota).

-- Nullable a propósito: filas viejas de program_enrollment_application (de una
-- DB de dev persistente) no tienen comprobante asociado. El código nuevo
-- siempre lo setea al crear la solicitud, pero la constraint no debe romper
-- una migración contra datos reales existentes.
alter table program_enrollment_application
    add column payment_receipt_id bigint references payment_receipt(id);

-- Inscripción a curso con pago: reemplaza la matriculación inmediata de la
-- Fase 2 — el CourseEnrollment real recién se crea cuando payment_receipt se
-- aprueba (ver PaymentReceiptService.aprobar). Mismo criterio de nombres
-- tácticos que program_enrollment_application.
create table course_enrollment_application (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    student_id bigint not null references student(id) on delete cascade,
    course_id bigint not null references course(id),
    section_overrides text,
    payment_receipt_id bigint not null unique references payment_receipt(id),
    course_enrollment_id bigint references course_enrollment(id)
);

create index ix_course_enrollment_application_student
    on course_enrollment_application (student_id);
