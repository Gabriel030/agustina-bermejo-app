create table broadcast (
    id bigint generated by default as identity primary key,
    name varchar(160) not null,
    category varchar(20) not null check (category in ('INSTITUTIONAL', 'PROMOTIONAL')),
    channel varchar(20) not null check (channel in ('EMAIL', 'WHATSAPP_LINK', 'WHATSAPP_API')),
    status varchar(20) not null check (status in ('DRAFT', 'CONFIRMED', 'SENDING', 'COMPLETED', 'CANCELLED')),
    segment_spec jsonb not null,
    subject_snapshot varchar(300),
    body_snapshot text not null,
    template_id bigint references message_template (id),
    created_by_person_id bigint not null references person (id),
    confirmed_by_person_id bigint references person (id),
    confirmed_at timestamptz,
    created_at timestamptz not null
);

create table broadcast_recipient (
    id bigint generated by default as identity primary key,
    broadcast_id bigint not null references broadcast (id),
    person_id bigint not null references person (id),
    status varchar(20) not null check (status in ('EXCLUDED', 'PENDING', 'QUEUED', 'SENT', 'FAILED', 'DONE', 'SKIPPED', 'INVALID_NUMBER')),
    exclusion_reason varchar(40) check (exclusion_reason in ('NO_VERIFIED_EMAIL', 'OPTED_OUT', 'NO_CONSENT', 'NO_VALID_PHONE', 'NO_CHANNEL_ADDRESS', 'MISSING_TEMPLATE_VARIABLE')),
    address_masked varchar(120),
    delivery_id bigint references notification_delivery (id),
    updated_at timestamptz not null,
    constraint uq_broadcast_recipient unique (broadcast_id, person_id),
    constraint ck_broadcast_recipient_reason check (status <> 'EXCLUDED' or exclusion_reason is not null)
);

create index ix_broadcast_recipient_status on broadcast_recipient (broadcast_id, status);
