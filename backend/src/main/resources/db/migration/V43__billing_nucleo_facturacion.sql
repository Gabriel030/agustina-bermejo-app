-- Fase 6.1: núcleo de facturación. Todas las entidades de precio/plan se versionan por fila
-- nueva (nunca UPDATE sobre una vigente) — createdBy/createdAt en cada una, sin tabla de
-- auditoría aparte.

create table price_revision (
    id bigint generated by default as identity,
    course_id bigint,
    program_id bigint,
    fee_type varchar(30) not null,
    description varchar(200) not null,
    monthly_amount numeric(12,2) not null,
    effective_from date not null,
    created_by_id bigint not null,
    created_at timestamp(6) not null,
    primary key (id),
    constraint fk_price_revision_course foreign key (course_id) references course,
    constraint fk_price_revision_program foreign key (program_id) references program,
    constraint fk_price_revision_created_by foreign key (created_by_id) references person
);

create index ix_price_revision_course on price_revision (course_id, fee_type, effective_from);
create index ix_price_revision_program on price_revision (program_id, fee_type, effective_from);

create table program_year_billing_template (
    id bigint generated by default as identity,
    program_id bigint not null,
    term_id bigint not null,
    tuition_invoices_count integer not null,
    created_by_id bigint not null,
    created_at timestamp(6) not null,
    primary key (id),
    constraint fk_pybt_program foreign key (program_id) references program,
    constraint fk_pybt_term foreign key (term_id) references term,
    constraint fk_pybt_created_by foreign key (created_by_id) references person,
    constraint uk_pybt_program_term unique (program_id, term_id)
);

-- Toda carrera abre exactamente 2 cohortes de inicio de cursada por año (FIRST/SECOND) — cada
-- una administrativamente independiente, con su propia ventana de admisión e inicio real de
-- cursada. Reemplaza la fecha de matrícula suelta que antes vivía en la plantilla anual.
create table program_cohort (
    id bigint generated by default as identity,
    template_id bigint not null,
    intake varchar(10) not null,
    admission_start date not null,
    admission_end date not null,
    cursada_start date not null,
    created_by_id bigint not null,
    created_at timestamp(6) not null,
    primary key (id),
    constraint fk_program_cohort_template foreign key (template_id) references program_year_billing_template,
    constraint fk_program_cohort_created_by foreign key (created_by_id) references person,
    constraint uk_program_cohort_intake unique (template_id, intake)
);

create table payment_plan_option (
    id bigint generated by default as identity,
    course_id bigint,
    program_id bigint,
    description varchar(200) not null,
    cadence varchar(20) not null,
    upfront_discount jsonb,
    upfront_window_enabled boolean not null default false,
    upfront_window_start date,
    upfront_window_end date,
    created_by_id bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint fk_ppo_course foreign key (course_id) references course,
    constraint fk_ppo_program foreign key (program_id) references program,
    constraint fk_ppo_created_by foreign key (created_by_id) references person,
    -- Encontrado en auditoría (2026-09-03): la spec pide este CHECK explícito ("análogo en
    -- PaymentPlanOption/PaymentPlanSelection") y había quedado sin agregar. A diferencia de
    -- Invoice, acá no hay caso ad-hoc — una opción siempre pertenece a un curso o una carrera.
    constraint chk_ppo_target check (num_nonnulls(course_id, program_id) = 1)
);

create table payment_plan_selection (
    id bigint generated by default as identity,
    course_enrollment_id bigint,
    program_enrollment_id bigint,
    payment_plan_option_id bigint not null,
    effective_from date not null,
    effective_to date,
    scope_months integer,
    created_by_id bigint not null,
    created_at timestamp(6) not null,
    primary key (id),
    constraint fk_pps_course_enrollment foreign key (course_enrollment_id) references course_enrollment,
    constraint fk_pps_program_enrollment foreign key (program_enrollment_id) references program_enrollment,
    constraint fk_pps_option foreign key (payment_plan_option_id) references payment_plan_option,
    constraint fk_pps_created_by foreign key (created_by_id) references person,
    -- Encontrado en auditoría (2026-09-03), mismo motivo que chk_ppo_target — una selección
    -- siempre pertenece a un enrollment real, nunca ad-hoc.
    constraint chk_pps_target check (num_nonnulls(course_enrollment_id, program_enrollment_id) = 1)
);

-- Solo una selección "abierta" (effective_to null) por billable a la vez.
create unique index uk_payment_plan_selection_open on payment_plan_selection
    (coalesce(course_enrollment_id, 0), coalesce(program_enrollment_id, 0))
    where effective_to is null;

-- Aggregate Root. course_enrollment_id/program_enrollment_id ambos null representa una Invoice
-- ad-hoc todavía no vinculada a ningún enrollment (Épica 7 Fase 3: la matrícula/primera cuota
-- se paga antes de que el enrollment exista) o, más adelante (Fase 6.7), una Invoice ad-hoc
-- de examen — nunca ambos a la vez.
create table invoice (
    id bigint generated by default as identity,
    version bigint not null default 0,
    course_enrollment_id bigint,
    program_enrollment_id bigint,
    payment_plan_selection_id bigint,
    fee_type varchar(30) not null,
    period date not null,
    due_date date not null,
    base_amount numeric(12,2) not null,
    status varchar(20) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    cancelled_by_id bigint,
    cancelled_reason varchar(500),
    cancelled_at timestamp(6),
    primary key (id),
    constraint fk_invoice_course_enrollment foreign key (course_enrollment_id) references course_enrollment,
    constraint fk_invoice_program_enrollment foreign key (program_enrollment_id) references program_enrollment,
    constraint fk_invoice_plan_selection foreign key (payment_plan_selection_id) references payment_plan_selection,
    constraint fk_invoice_cancelled_by foreign key (cancelled_by_id) references person,
    constraint chk_invoice_billable check (num_nonnulls(course_enrollment_id, program_enrollment_id) <= 1)
);

-- coalesce(...,0): Postgres nunca trata dos NULL como iguales en un índice único, así que sin
-- esto la unicidad se rompería en silencio en el caso normal (course_enrollment_id seteado,
-- program_enrollment_id NULL, o viceversa) — mismo criterio que uk_payment_plan_selection_open.
-- El "and (... is not null or ... is not null)" deja afuera del índice a las Invoice ad-hoc
-- (Épica 7 Fase 3: matrícula/primera cuota pagada antes de que el enrollment exista, ver
-- InvoiceFactory.crearAdHocPara*) — esas SÍ pueden repetir feeType+period entre sí (son de
-- alumnos/solicitudes distintas), coalescer ahí las haría chocar entre sí por error.
create unique index uk_invoice_billable_period on invoice
    (coalesce(course_enrollment_id, 0), coalesce(program_enrollment_id, 0), fee_type, period)
    where fee_type in ('TUITION', 'ENROLLMENT_FEE', 'SUBSCRIPTION_FEE')
      and (course_enrollment_id is not null or program_enrollment_id is not null);

create index ix_invoice_course_enrollment on invoice (course_enrollment_id);
create index ix_invoice_program_enrollment on invoice (program_enrollment_id);

create table invoice_adjustment (
    id bigint generated by default as identity,
    invoice_id bigint not null,
    type varchar(30) not null,
    value jsonb not null,
    resolved_base numeric(12,2) not null,
    reason varchar(500) not null,
    applied_by_id bigint,
    applied_at timestamp(6) not null,
    primary key (id),
    constraint fk_invoice_adjustment_invoice foreign key (invoice_id) references invoice,
    constraint fk_invoice_adjustment_applied_by foreign key (applied_by_id) references person
);

