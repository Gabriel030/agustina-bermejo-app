-- matriculación — mismo criterio que usa la industria para "cohort year/term": identifica cuándo
-- entró el alumno, nunca en qué año de cursada está ahora). Un alumno puede repetir un año
-- (rendir de nuevo las mismas materias), así que la cantidad de años facturados no tiene por qué
-- coincidir con Program.totalYears — este campo es lo único que avanza con el tiempo.
