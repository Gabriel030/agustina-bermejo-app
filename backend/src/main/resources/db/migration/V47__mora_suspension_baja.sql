    add column billing_standing_updated_at timestamp(6);
alter table program_enrollment add column billing_standing varchar(30) not null default 'UP_TO_DATE',
    add column billing_standing_updated_at timestamp(6);

create table batch_execution_log (
    id bigint generated by default as identity,
    job_name varchar(100) not null,
    ran_at timestamp(6) not null,
    duration_ms bigint not null,
    candidate_count integer not null,
    processed_count integer not null,
    failed_count integer not null,
    status varchar(20) not null,
    errors text,
    primary key (id)
);

create index ix_batch_execution_log_job_name on batch_execution_log (job_name, ran_at);
