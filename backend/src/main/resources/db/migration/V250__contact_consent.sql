create table contact_consent (
    id bigint generated by default as identity primary key,
    person_id bigint not null references person (id),
    channel varchar(20) not null check (channel in ('EMAIL', 'WHATSAPP_LINK', 'WHATSAPP_API')),
    category varchar(20) not null check (category in ('INSTITUTIONAL', 'PROMOTIONAL')),
    status varchar(10) not null check (status in ('GRANTED', 'REVOKED')),
    source varchar(20) not null check (source in ('PROFILE', 'EMAIL_LINK', 'STAFF_ON_BEHALF', 'IMPORT')),
    evidence varchar(200),
    recorded_at timestamptz not null,
    constraint uq_contact_consent unique (person_id, channel, category)
);

create index ix_contact_consent_person on contact_consent (person_id);

alter table audit_log drop constraint ck_audit_log_action;

