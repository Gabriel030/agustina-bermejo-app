create table classroom (
    id       bigint generated by default as identity,
    name     varchar(255) not null,
    capacity integer      not null,
    status   varchar(20)  not null default 'ACTIVE',
    primary key (id),
    constraint uk_classroom_name unique (name)
);

create table section_schedule_slot (
    id                 bigint generated by default as identity,
    subject_section_id bigint references subject_section (id),
    course_section_id  bigint references course_section (id),
    classroom_id       bigint not null references classroom (id),
    day_of_week        varchar(10) not null,
    start_time         time        not null,
    end_time           time        not null,
    primary key (id),
    constraint chk_schedule_slot_exactly_one_section
        check (
            (subject_section_id is not null and course_section_id is null) or
            (subject_section_id is null and course_section_id is not null)
        ),
    constraint chk_schedule_slot_valid_range check (end_time > start_time)
);

create index ix_schedule_slot_classroom_day on section_schedule_slot (classroom_id, day_of_week);
