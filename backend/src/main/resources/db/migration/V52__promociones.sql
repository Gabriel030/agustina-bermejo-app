create table promotion (
    id bigint generated by default as identity,
    description varchar(200) not null,
    course_id bigint,
    program_id bigint,
    eligibility_valid_from date not null,
    eligibility_valid_to date not null,
    status varchar(20) not null,
    created_by_id bigint not null,
    created_at timestamp(6) not null,
    closed_by_id bigint,
    closed_at timestamp(6),
    primary key (id),
    constraint chk_promotion_scope check (num_nonnulls(course_id, program_id) = 1),
    constraint fk_promotion_course foreign key (course_id) references course,
    constraint fk_promotion_program foreign key (program_id) references program,
    constraint fk_promotion_created_by foreign key (created_by_id) references person,
    constraint fk_promotion_closed_by foreign key (closed_by_id) references person
);

create table promotion_benefit (
    id bigint generated by default as identity,
    promotion_id bigint not null,
    fee_type varchar(30) not null,
    value jsonb not null,
    invoice_scope_count int,
    primary key (id),
    constraint fk_promotion_benefit_promotion foreign key (promotion_id) references promotion
);

create table promotion_redemption (
    id bigint generated by default as identity,
    promotion_id bigint not null,
    payment_plan_selection_id bigint not null,
    redeemed_at timestamp(6) not null,
    primary key (id),
    constraint fk_pr_promotion foreign key (promotion_id) references promotion,
    constraint fk_pr_payment_plan_selection foreign key (payment_plan_selection_id) references payment_plan_selection,
    constraint uk_promotion_redemption_selection unique (payment_plan_selection_id)
);

alter table invoice_adjustment
    add column promotion_benefit_id bigint,
    add constraint fk_ia_promotion_benefit foreign key (promotion_benefit_id) references promotion_benefit;
