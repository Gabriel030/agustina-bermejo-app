create table enrollment_payment_standing (
    id bigint generated by default as identity,
    version bigint not null default 0,
    program_enrollment_id bigint,
    course_enrollment_id bigint,
    student_id bigint not null,
    status varchar(30) not null,
    suspended_since date,
    primary key (id),
    constraint fk_enrollment_payment_standing_program foreign key (program_enrollment_id) references program_enrollment (id),
    constraint fk_enrollment_payment_standing_course foreign key (course_enrollment_id) references course_enrollment (id),
    constraint fk_enrollment_payment_standing_student foreign key (student_id) references student (id),
    constraint ck_enrollment_payment_standing_one_enrollment check (num_nonnulls(program_enrollment_id, course_enrollment_id) = 1),
    constraint ck_enrollment_payment_standing_status check (status in ('UP_TO_DATE', 'OVERDUE', 'SUSPENDED', 'WITHDRAWN_FOR_NONPAYMENT')),
    constraint ck_enrollment_payment_standing_suspended_since check ((status = 'SUSPENDED') = (suspended_since is not null))
);

create unique index uk_enrollment_payment_standing_program on enrollment_payment_standing (program_enrollment_id) where program_enrollment_id is not null;
create unique index uk_enrollment_payment_standing_course on enrollment_payment_standing (course_enrollment_id) where course_enrollment_id is not null;
create index ix_enrollment_payment_standing_student on enrollment_payment_standing (student_id);
create index ix_enrollment_payment_standing_status on enrollment_payment_standing (status);

create table enrollment_payment_status_change (
    id bigint generated by default as identity,
    standing_id bigint not null,
    event varchar(60) not null,
    from_status varchar(30),
    to_status varchar(30) not null,
    reason varchar(500),
    actor_person_id bigint,
    actor_process varchar(80),
    business_date date not null,
    occurred_at timestamp(6) not null,
    primary key (id),
    constraint fk_enrollment_payment_status_change_standing foreign key (standing_id) references enrollment_payment_standing (id),
    constraint fk_enrollment_payment_status_change_actor foreign key (actor_person_id) references person (id),
    constraint ck_enrollment_payment_status_change_actor check (num_nonnulls(actor_person_id, actor_process) = 1)
);

create index ix_enrollment_payment_status_change_standing on enrollment_payment_status_change (standing_id, id);

create trigger trg_enrollment_payment_status_change_append_only before update or delete on enrollment_payment_status_change
    for each row execute function forbid_append_only_row_change();

insert into enrollment_payment_standing (program_enrollment_id, student_id, status, suspended_since)
select e.id, e.student_id, e.payment_status,
       case when e.payment_status = 'SUSPENDED' then date_trunc('month', coalesce(e.payment_status_updated_at, now()))::date end
from program_enrollment e
where e.student_id is not null;

insert into enrollment_payment_standing (course_enrollment_id, student_id, status, suspended_since)
