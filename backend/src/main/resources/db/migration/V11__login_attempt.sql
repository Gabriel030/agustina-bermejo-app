-- RF-AUTH-08: auditoría de accesos (login exitoso/fallido, IP, fecha/hora).
-- person_id es nullable a propósito: un intento con un username inexistente no tiene
-- persona asociada, pero igual se audita para poder detectar fuerza bruta.
create table login_attempt (
    id bigint generated by default as identity,
    person_id bigint,
    attempted_username varchar(255),
    successful boolean not null,
    ip_address varchar(45),
    attempted_at timestamp not null,
    primary key (id),
    constraint fk_login_attempt_person foreign key (person_id) references person on delete cascade
);
