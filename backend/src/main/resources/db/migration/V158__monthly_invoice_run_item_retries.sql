alter table monthly_invoice_run_item drop constraint ck_monthly_invoice_run_item_result;
alter table monthly_invoice_run_item add constraint ck_monthly_invoice_run_item_result
    check (result in ('ISSUED', 'NOT_APPLICABLE', 'ALREADY_ISSUED', 'FAILED', 'RETRIES_EXHAUSTED'));

create table monthly_invoice_run_item_attempt (
    id bigint generated by default as identity,
    monthly_invoice_run_item_id bigint not null,
    attempt_number int not null,
    attempted_at timestamp(6) not null,
    result varchar(20) not null,
    error_code varchar(60),
    message varchar(500),
    primary key (id),
    constraint fk_monthly_invoice_run_item_attempt_item foreign key (monthly_invoice_run_item_id) references monthly_invoice_run_item (id) on delete cascade,
    constraint uq_run_item_attempt unique (monthly_invoice_run_item_id, attempt_number),
    constraint ck_monthly_invoice_run_item_attempt_number check (attempt_number >= 1),
    constraint ck_monthly_invoice_run_item_attempt_result check (result in ('ISSUED', 'NOT_APPLICABLE', 'ALREADY_ISSUED', 'FAILED'))
);
