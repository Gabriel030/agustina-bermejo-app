-- EvaluationScheme: fuera los 11 campos planos sin uso (confirmado por grep exhaustivo: ningún
-- service los lee ni escribe desde que se creó la entidad), dentro los umbrales que el algoritmo
-- de recálculo de resultado de cursada realmente necesita. Se usa un piso institucional fijo
-- (4 para quedar regular, 6 para aprobar) en vez de dejarlos null hasta configurar por comisión.
alter table evaluation_scheme
    drop column first_exam, drop column first_exam_recovery,
    drop column second_exam, drop column second_exam_recovery,
    drop column third_exam, drop column third_exam_recovery,
    drop column final_exam,
    drop column final_exam_recovery_first_attempt,
    drop column final_exam_recovery_second_attempt,
    drop column final_exam_recovery_third_attempt,
    drop column general_average,
    add column min_regular_grade float(53) not null default 4.0,
    add column min_approval_grade float(53) not null default 6.0;

-- "Libre por inasistencias" se calcula siempre en el momento de la consulta (nunca persistido);
-- el porcentaje máximo de ausentismo permitido se configura por comisión.
alter table program_section add column max_absence_percentage float(53);
alter table course_section add column max_absence_percentage float(53);

-- Tope de reintentos para rendir el final de una materia: configurable por materia (no por
-- comisión, ya que las mesas de examen se organizan por materia+período). Null = sin límite.
alter table subject add column max_final_exam_attempts integer;
alter table course_subject add column max_final_exam_attempts integer;

alter table grade_item add column exam_board_id bigint;

create table attendance (
    id bigint generated by default as identity, version bigint not null default 0,
    course_section_enrollment_id bigint, program_section_enrollment_id bigint,
    class_date date not null, status varchar(20) not null,
    recorded_by_id bigint not null,
    justification_reason varchar(500), justification_attachment_url varchar(255),
    justified_by_id bigint, justified_at timestamp(6),
    primary key (id),
    constraint chk_attendance_single_target check (
        (course_section_enrollment_id is not null and program_section_enrollment_id is null)
        or (course_section_enrollment_id is null and program_section_enrollment_id is not null)
    ),
    constraint fk_attendance_course_enr foreign key (course_section_enrollment_id) references course_section_enrollment,
    constraint fk_attendance_program_enr foreign key (program_section_enrollment_id) references program_section_enrollment,
    constraint fk_attendance_recorded_by foreign key (recorded_by_id) references instructor,
    constraint fk_attendance_justified_by foreign key (justified_by_id) references person
);

-- Sin duplicados: un registro por alumno+comisión+fecha, un índice único parcial por cada lado
-- del XOR (no se puede hacer un único constraint sobre columnas nullable con NULLs distintos).
create unique index uk_attendance_course_date on attendance (course_section_enrollment_id, class_date)
    where course_section_enrollment_id is not null;
create unique index uk_attendance_program_date on attendance (program_section_enrollment_id, class_date)
    where program_section_enrollment_id is not null;

create table exam_board (
    id bigint generated by default as identity, version bigint not null default 0,
    subject_id bigint, course_subject_id bigint, term_id bigint not null,
    exam_date timestamp(6) not null, registration_start timestamp(6), registration_end timestamp(6),
    status varchar(20) not null,
    primary key (id),
    constraint chk_exam_board_single_target check (
        (subject_id is not null and course_subject_id is null)
        or (subject_id is null and course_subject_id is not null)
    ),
    constraint fk_exam_board_subject foreign key (subject_id) references subject,
    constraint fk_exam_board_course_subject foreign key (course_subject_id) references course_subject,
    constraint fk_exam_board_term foreign key (term_id) references term
);

alter table grade_item add constraint fk_grade_item_exam_board foreign key (exam_board_id) references exam_board;

create table exam_board_instructor (
    id bigint generated by default as identity,
    exam_board_id bigint not null, instructor_id bigint not null,
    primary key (id),
    constraint fk_ebi_exam_board foreign key (exam_board_id) references exam_board on delete cascade,
    constraint fk_ebi_instructor foreign key (instructor_id) references instructor,
    constraint uk_ebi_board_instructor unique (exam_board_id, instructor_id)
);

create table exam_board_registration (
    id bigint generated by default as identity, version bigint not null default 0,
    exam_board_id bigint not null,
    program_section_enrollment_id bigint, course_section_enrollment_id bigint,
    status varchar(20) not null, registered_at timestamp(6) not null,
    primary key (id),
    constraint chk_ebr_single_target check (
        (program_section_enrollment_id is not null and course_section_enrollment_id is null)
        or (program_section_enrollment_id is null and course_section_enrollment_id is not null)
    ),
    constraint fk_ebr_exam_board foreign key (exam_board_id) references exam_board,
    constraint fk_ebr_program_enr foreign key (program_section_enrollment_id) references program_section_enrollment,
    constraint fk_ebr_course_enr foreign key (course_section_enrollment_id) references course_section_enrollment
);

create unique index uk_ebr_board_program_enr on exam_board_registration (exam_board_id, program_section_enrollment_id)
    where program_section_enrollment_id is not null;
create unique index uk_ebr_board_course_enr on exam_board_registration (exam_board_id, course_section_enrollment_id)
    where course_section_enrollment_id is not null;
