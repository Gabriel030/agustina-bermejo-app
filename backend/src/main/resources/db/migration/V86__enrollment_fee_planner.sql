create table enrollment_fee_exemption (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    program_enrollment_id bigint not null references program_enrollment (id),
    template_id bigint not null references program_year_billing_template (id),
    slot integer not null check (slot in (1, 2)),
    reason varchar(1000) not null,
    granted_by_id bigint not null references person (id),
    granted_at timestamp(6) not null,
    revoked_by_id bigint references person (id),
    revoked_at timestamp(6),
    revocation_notes varchar(500)
);
create unique index uk_enrollment_fee_exemption_active
    on enrollment_fee_exemption (program_enrollment_id, template_id, slot) where revoked_at is null;
create index ix_enrollment_fee_exemption_enrollment on enrollment_fee_exemption (program_enrollment_id);

