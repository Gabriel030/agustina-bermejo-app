create table discount_definition (
    id bigint generated by default as identity primary key,
    name varchar(200) not null,
    discount_type varchar(20) not null check (discount_type in ('SCHOLARSHIP', 'COHORT_PROMOTION', 'ANNUAL_UPFRONT', 'PAYMENT_METHOD')),
    applicable_invoice_type varchar(30) not null check (applicable_invoice_type in ('MONTHLY_INSTALLMENT', 'ANNUAL_UPFRONT', 'ENROLLMENT_FEE',
        'EXAM_FEE', 'RETAKEN_SUBJECT_FEE', 'DEGREE_ISSUANCE_FEE', 'ADMINISTRATIVE_FEE')),
    calculation jsonb,
    installments_total integer check (installments_total >= 1),
    available_from date not null,
    available_until date,
    priority integer not null check (priority >= 1),
    cap_per_invoice numeric(12, 2) check (cap_per_invoice > 0),
    cap_per_invoice_currency varchar(3) check (cap_per_invoice_currency in ('ARS', 'USD')),
    program_id bigint references program (id),
    program_cohort_id bigint references program_cohort (id),
    course_id bigint references course (id),
    enrollment_window_from date,
    enrollment_window_to date,
    quota integer check (quota >= 1),
    quota_exhausted_notified_at timestamptz,
    status varchar(10) not null check (status in ('ACTIVE', 'CLOSED')),
    created_by_id bigint references person (id),
    created_by_process varchar(80),
    created_at timestamptz not null,
    direct_publication boolean not null,
    authorization_request_id bigint references authorization_request (id),
    closed_by_id bigint references person (id),
    closed_at timestamptz,
    closure_reason varchar(1000),
    version bigint not null default 0,
    constraint ck_discount_definition_available_period check (available_until is null or available_until >= available_from),
    constraint ck_discount_definition_enrollment_window check (enrollment_window_to is null or enrollment_window_from is null or enrollment_window_to >= enrollment_window_from),
    constraint ck_discount_definition_single_offering check (num_nonnulls(program_id, course_id) <= 1),
    constraint ck_discount_definition_cohort_needs_program check (program_cohort_id is null or program_id is not null),
    constraint ck_discount_definition_scope_only_cohort_promotion check (discount_type = 'COHORT_PROMOTION'
        or num_nonnulls(program_id, program_cohort_id, course_id, enrollment_window_from, enrollment_window_to, quota) = 0),
    constraint ck_discount_definition_calculation_required check (calculation is not null or discount_type = 'SCHOLARSHIP'),
    constraint ck_discount_definition_installments_monthly check (installments_total is null or applicable_invoice_type = 'MONTHLY_INSTALLMENT'),
    constraint ck_discount_definition_scholarship_monthly check (discount_type <> 'SCHOLARSHIP' or applicable_invoice_type = 'MONTHLY_INSTALLMENT'),
    constraint ck_discount_definition_annual_upfront check (discount_type <> 'ANNUAL_UPFRONT' or applicable_invoice_type = 'ANNUAL_UPFRONT'),
    constraint ck_discount_definition_cap_currency check ((cap_per_invoice is null) = (cap_per_invoice_currency is null)),
    constraint ck_discount_definition_creator check (num_nonnulls(created_by_id, created_by_process) = 1),
    constraint ck_discount_definition_closure check ((status = 'CLOSED') = (closed_at is not null))
);

create index ix_discount_definition_status_type on discount_definition (status, discount_type);
create index ix_discount_definition_program on discount_definition (program_id) where program_id is not null;
create index ix_discount_definition_course on discount_definition (course_id) where course_id is not null;
create index ix_discount_definition_authorization_request on discount_definition (authorization_request_id) where authorization_request_id is not null;

create table discount_definition_status_change (
    id bigint generated by default as identity primary key,
    discount_definition_id bigint not null references discount_definition (id),
    from_status varchar(10),
    to_status varchar(10) not null,
    event varchar(30) not null,
    actor_person_id bigint references person (id),
    actor_process varchar(80),
    changed_at timestamptz not null,
    reason varchar(1000),
    check ((actor_person_id is null) <> (actor_process is null))
);

create index ix_discount_definition_status_change_definition on discount_definition_status_change (discount_definition_id);

create trigger trg_discount_definition_status_change_append_only before update or delete on discount_definition_status_change
    for each row execute function forbid_append_only_row_change();

create function forbid_discount_definition_value_change() returns trigger language plpgsql as $$
begin
    if new.name is distinct from old.name
        or new.discount_type is distinct from old.discount_type
        or new.applicable_invoice_type is distinct from old.applicable_invoice_type
        or new.calculation is distinct from old.calculation
        or new.installments_total is distinct from old.installments_total
        or new.available_from is distinct from old.available_from
        or new.available_until is distinct from old.available_until
        or new.priority is distinct from old.priority
        or new.cap_per_invoice is distinct from old.cap_per_invoice
        or new.cap_per_invoice_currency is distinct from old.cap_per_invoice_currency
        or new.program_id is distinct from old.program_id
        or new.program_cohort_id is distinct from old.program_cohort_id
        or new.course_id is distinct from old.course_id
        or new.enrollment_window_from is distinct from old.enrollment_window_from
        or new.enrollment_window_to is distinct from old.enrollment_window_to
        or new.quota is distinct from old.quota then
        raise exception 'The values of a discount definition cannot change; close it and create another one';
    end if;
    return new;
end;
$$;

create trigger trg_discount_definition_value_immutable before update on discount_definition
    for each row execute function forbid_discount_definition_value_change();

