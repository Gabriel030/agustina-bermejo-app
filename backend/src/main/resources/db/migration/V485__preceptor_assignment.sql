create table preceptor_assignment (
    id bigint generated by default as identity primary key,
    person_id bigint not null references person (id) on delete cascade,
    program_id bigint references program (id) on delete cascade,
    course_id bigint references course (id) on delete cascade,
    created_at timestamp(6) not null default now(),
    constraint preceptor_assignment_target_check check ((program_id is null) <> (course_id is null))
);

create unique index preceptor_assignment_person_program_uq on preceptor_assignment (person_id, program_id) where program_id is not null;
create unique index preceptor_assignment_person_course_uq on preceptor_assignment (person_id, course_id) where course_id is not null;
create index preceptor_assignment_person_idx on preceptor_assignment (person_id);
