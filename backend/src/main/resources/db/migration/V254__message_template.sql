create table message_template (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    category varchar(20) not null check (category in ('INSTITUTIONAL', 'PROMOTIONAL')),
    channel varchar(20) not null check (channel in ('EMAIL', 'WHATSAPP_LINK', 'WHATSAPP_API')),
    subject varchar(300),
    body_text text not null,
    active boolean not null default true,
    created_by_person_id bigint not null references person (id),
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint ck_message_template_email_subject check (channel <> 'EMAIL' or subject is not null)
);

create index ix_message_template_active_channel on message_template (active, channel, category);
