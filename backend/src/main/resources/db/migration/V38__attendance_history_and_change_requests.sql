-- Docente · Tomar asistencia (Épica 3, Fase 1): "clase" puntual de una comisión (para temario,
-- observaciones y cancelación, sin modelar aula/horario todavía) y workflow de solicitud de
-- modificación de una asistencia ya cargada.

create table class_session (
    id bigint generated by default as identity, version bigint not null default 0,
    program_section_id bigint, course_section_id bigint,
    class_date date not null, status varchar(20) not null,
    topic varchar(1000), observations varchar(500),
    classroom varchar(255), start_time time, end_time time,
    created_by_id bigint not null, created_at timestamp(6) not null,
    primary key (id),
    constraint chk_class_session_single_target check (
        (program_section_id is not null and course_section_id is null)
        or (program_section_id is null and course_section_id is not null)
    ),
    constraint fk_class_session_program foreign key (program_section_id) references subject_section,
    constraint fk_class_session_course foreign key (course_section_id) references course_section,
    constraint fk_class_session_created_by foreign key (created_by_id) references instructor
);

create unique index uk_class_session_program_date on class_session (program_section_id, class_date)
    where program_section_id is not null;
create unique index uk_class_session_course_date on class_session (course_section_id, class_date)
    where course_section_id is not null;

create table attendance_change_request (
    id bigint generated by default as identity, version bigint not null default 0,
    attendance_id bigint not null, requested_by_id bigint not null,
    previous_status varchar(30) not null, requested_status varchar(30) not null,
    reason varchar(500) not null, status varchar(20) not null,
    approved_by_id bigint, approved_at timestamp(6),
    created_at timestamp(6) not null,
    primary key (id),
    constraint fk_acr_attendance foreign key (attendance_id) references attendance,
    constraint fk_acr_requested_by foreign key (requested_by_id) references instructor,
    constraint fk_acr_approved_by foreign key (approved_by_id) references person
);
