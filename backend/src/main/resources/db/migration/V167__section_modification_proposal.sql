create table section_modification_proposal (
    id                 bigint generated by default as identity primary key,
    subject_section_id bigint       not null references subject_section (id),
    status             varchar(20)  not null,
    replaces_schedule  boolean      not null,
    requested_at       timestamp(6) not null,
    resolved_at        timestamp(6),
    rejection_reason   varchar(1000),
    constraint ck_section_modification_proposal_status check (status in ('PENDING', 'APPROVED', 'REJECTED'))
);

create unique index uq_section_modification_proposal_pending
    on section_modification_proposal (subject_section_id) where status = 'PENDING';

create index idx_section_modification_proposal_section
    on section_modification_proposal (subject_section_id, id desc);

create table section_modification_proposal_slot (
    proposal_id  bigint      not null references section_modification_proposal (id) on delete cascade,
    classroom_id bigint      not null references classroom (id),
    day_of_week  varchar(10) not null,
    start_time   time        not null,
    end_time     time        not null
);

create index idx_section_modification_proposal_slot_classroom
    on section_modification_proposal_slot (classroom_id);

insert into section_modification_proposal (subject_section_id, status, replaces_schedule, requested_at)
select id, 'PENDING', false, now()
from subject_section
where pending_approval = true;
