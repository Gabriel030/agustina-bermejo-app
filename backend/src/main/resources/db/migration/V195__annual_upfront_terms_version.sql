create table annual_upfront_terms_version (
    id bigint generated by default as identity primary key,
    version_number integer not null,
    text text not null,
    published_by_person_id bigint references person,
    published_at timestamp(6) not null,
    constraint uq_annual_upfront_terms_version_number unique (version_number),
    constraint ck_annual_upfront_terms_version_number_positive check (version_number > 0),
    constraint ck_annual_upfront_terms_text_length check (char_length(text) between 50 and 20000)
);

