create table annual_upfront_request (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    program_enrollment_id bigint not null references program_enrollment (id),
    lective_year_term_id bigint not null references term (id),
    invoice_id bigint not null unique references invoice (id),
    status varchar(24) not null check (status in ('AWAITING_PAYMENT', 'PAYMENT_UNDER_REVIEW', 'CONFIRMED', 'DISCARDED')),
    discard_reason varchar(24) check (discard_reason in ('DEADLINE_EXPIRED', 'PAYMENT_REJECTED', 'WITHDRAWAL', 'CANCELLED_BY_STUDENT')),
    payment_id bigint,
    requested_by_person_id bigint not null references person (id),
    requested_at timestamp(6) not null,
    accepted_terms_version varchar(20) not null,
    accepted_terms_text text not null,
    accepted_at timestamp(6) not null,
    accepted_by_person_id bigint not null references person (id),
    decided_at timestamp(6),
    constraint ck_annual_upfront_request_discard check ((status = 'DISCARDED') = (discard_reason is not null))
);

create unique index uk_annual_upfront_request_open on annual_upfront_request (program_enrollment_id, lective_year_term_id)
    where status in ('AWAITING_PAYMENT', 'PAYMENT_UNDER_REVIEW', 'CONFIRMED');
create index ix_annual_upfront_request_deadline on annual_upfront_request (status) where status = 'AWAITING_PAYMENT';

