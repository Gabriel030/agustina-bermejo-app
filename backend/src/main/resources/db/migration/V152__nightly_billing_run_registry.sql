create table nightly_billing_run (
    id bigint generated by default as identity,
    business_date date not null,
    status varchar(30) not null,
    trigger varchar(12) not null,
    started_at timestamp(6) not null,
    finished_at timestamp(6),
    primary key (id),
    constraint uq_nightly_billing_run_date unique (business_date),
    constraint ck_nightly_billing_run_status check (status in ('RUNNING', 'COMPLETED', 'COMPLETED_WITH_ERRORS', 'FAILED')),
    constraint ck_nightly_billing_run_trigger check (trigger in ('SCHEDULED', 'MANUAL')),
    constraint ck_nightly_billing_run_finished check ((status = 'RUNNING') = (finished_at is null))
);

create table billing_run (
    id bigint generated by default as identity,
    nightly_billing_run_id bigint not null,
    step varchar(40) not null,
    status varchar(30) not null,
    candidates int not null default 0,
    processed int not null default 0,
    skipped int not null default 0,
    failed int not null default 0,
    not_applicable_code varchar(40),
    started_at timestamp(6),
    finished_at timestamp(6),
    primary key (id),
    constraint fk_billing_run_nightly foreign key (nightly_billing_run_id) references nightly_billing_run (id),
    constraint uq_billing_run_step unique (nightly_billing_run_id, step),
    constraint ck_billing_run_status check (status in ('RUNNING', 'COMPLETED', 'COMPLETED_WITH_ERRORS', 'FAILED', 'NOT_APPLICABLE')),
    constraint ck_billing_run_counts check (candidates >= 0 and processed >= 0 and skipped >= 0 and failed >= 0),
    constraint ck_billing_run_not_applicable_code check ((status = 'NOT_APPLICABLE') = (not_applicable_code is not null))
);

create table billing_run_item (
    id bigint generated by default as identity,
    billing_run_id bigint not null,
    subject_type varchar(30) not null,
    subject_id bigint not null,
    status varchar(12) not null,
    decision_code varchar(60),
    error_code varchar(60),
    message varchar(500),
    primary key (id),
    constraint fk_billing_run_item_run foreign key (billing_run_id) references billing_run (id),
    constraint uq_billing_run_item_subject unique (billing_run_id, subject_type, subject_id),
    constraint ck_billing_run_item_status check (status in ('SKIPPED', 'FAILED'))
);
