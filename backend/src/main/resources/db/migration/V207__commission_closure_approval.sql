create table closure_report_number_counter (
    report_year integer primary key,
    last_number integer not null check (last_number >= 1)
);

alter table commission_closure_audit drop constraint ck_commission_closure_audit_action;
alter table commission_closure_audit add constraint ck_commission_closure_audit_action check (
    action in ('CONFIRMED_BY_TEACHER', 'CLOSED', 'CLOSED_WITHOUT_TEACHER_CONFIRMATION', 'REOPENED',
               'EXCEPTION_GRANTED', 'EXCEPTION_REVOKED'));

create table commission_closure_exception (
    id bigint generated by default as identity primary key,
    closure_id bigint not null references commission_closure (id),
    enrollment_id bigint not null,
    reason varchar(500) not null,
    granted_by_person_id bigint not null references person (id),
    granted_at timestamp(6) not null,
    revoked_by_person_id bigint references person (id),
    revoked_at timestamp(6)
);

create unique index uq_commission_closure_exception_active
    on commission_closure_exception (closure_id, enrollment_id) where revoked_at is null;
