create table informative_session (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    title varchar(200) not null,
    scheduled_at timestamp(6) not null,
    modality varchar(20) not null,
    meeting_url varchar(500),
    location varchar(255),
    capacity integer,
    related_program_id bigint references program (id),
    status varchar(20) not null,
    created_by_id bigint not null references person (id),
    created_at timestamp(6) not null,
    constraint informative_session_modality_enum check (modality in ('ONLINE', 'IN_PERSON')),
    constraint informative_session_status_enum check (status in ('SCHEDULED', 'CANCELLED', 'COMPLETED')),
    constraint ck_informative_session_title check (length(trim(title)) > 0),
    constraint ck_informative_session_capacity check (capacity is null or capacity > 0)
);

create index ix_informative_session_scheduled on informative_session (status, scheduled_at);
create index ix_informative_session_program on informative_session (related_program_id);
create index ix_informative_session_created_by on informative_session (created_by_id);

create table informative_session_registration (
    id bigint generated by default as identity primary key,
    session_id bigint not null references informative_session (id),
    person_id bigint not null references person (id),
    created_at timestamp(6) not null,
    constraint uk_informative_session_registration unique (session_id, person_id)
);

create index ix_informative_session_registration_person on informative_session_registration (person_id);

insert into permission (code, module, description, fixed_to_director, sensitive) values
    ('informative_session.manage', 'informative_session', 'Crear, editar y cancelar charlas informativas', false, false);

insert into role_permission (role, permission_id)
select grants.role, permission.id
from (values
    ('PRECEPTOR', 'informative_session.manage')
) as grants (role, code)
join permission on permission.code = grants.code;
