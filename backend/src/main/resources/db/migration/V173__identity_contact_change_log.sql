alter table email_verification_token add column new_email varchar(255);

create table identity_contact_change_log (
    id bigint generated by default as identity primary key,
    person_id bigint not null references person on delete cascade,
    actor_person_id bigint not null references person,
    change_type varchar(40) not null,
    old_value varchar(255),
    new_value varchar(255),
    occurred_at timestamp(6) not null
);

create index ix_identity_contact_change_log_person on identity_contact_change_log (person_id, occurred_at desc);
