alter table payment_allocation add constraint uk_payment_allocation_id_account unique (id, student_current_account_id);
alter table payment_allocation add constraint uk_payment_allocation_id_currency unique (id, amount_currency);

create table payment_allocation_source (
    id bigint generated by default as identity primary key,
    payment_allocation_id bigint not null,
    student_current_account_id bigint not null,
    credit_entry_id bigint not null,
    payment_id bigint,
    credit_note_id bigint,
    amount numeric(12, 2) not null check (amount > 0),
    amount_currency varchar(3) not null check (amount_currency in ('ARS', 'USD')),
    reverses_source_id bigint,
    recorded_at timestamp(6) not null,
    constraint uk_payment_allocation_source_reverses unique (reverses_source_id),
    constraint fk_payment_allocation_source_reverses foreign key (reverses_source_id) references payment_allocation_source (id),
    constraint fk_payment_allocation_source_allocation_account foreign key (payment_allocation_id, student_current_account_id)
        references payment_allocation (id, student_current_account_id),
    constraint fk_payment_allocation_source_allocation_currency foreign key (payment_allocation_id, amount_currency)
        references payment_allocation (id, amount_currency),
    constraint fk_payment_allocation_source_entry_account foreign key (credit_entry_id, student_current_account_id)
        references current_account_entry (id, student_current_account_id),
    constraint ck_payment_allocation_source_exactly_one_origin check (num_nonnulls(payment_id, credit_note_id) = 1)
);

create index ix_payment_allocation_source_allocation on payment_allocation_source (payment_allocation_id);
create index ix_payment_allocation_source_entry on payment_allocation_source (credit_entry_id);

create function forbid_inconsistent_payment_allocation_source() returns trigger language plpgsql as $$
declare
    allocation_reverses bigint;
begin
    select reverses_allocation_id into allocation_reverses from payment_allocation where id = new.payment_allocation_id;
    if not exists (select 1 from current_account_entry e
                   where e.id = new.credit_entry_id and e.amount_currency = new.amount_currency
                     and ((e.entry_type = 'PAYMENT_RECEIVED' and e.payment_id = new.payment_id)
                          or (e.entry_type = 'CREDIT_NOTE_ISSUED' and e.credit_note_id = new.credit_note_id))) then
        raise exception 'the source of an allocation must be a payment or credit note credit entry of the same account and currency'
            using errcode = 'integrity_constraint_violation';
    end if;
    if allocation_reverses is null then
        if new.reverses_source_id is not null then
            raise exception 'a source of an allocation cannot reverse another source' using errcode = 'integrity_constraint_violation';
        end if;
    elsif not exists (select 1 from payment_allocation_source o
                      where o.id = new.reverses_source_id and o.reverses_source_id is null and o.payment_allocation_id = allocation_reverses
                        and o.credit_entry_id = new.credit_entry_id and o.amount = new.amount and o.amount_currency = new.amount_currency) then
        raise exception 'a source of a reversal must undo a source of the reversed allocation' using errcode = 'integrity_constraint_violation';
    end if;
    return new;
end;
$$;

create trigger trg_payment_allocation_source_consistent before insert on payment_allocation_source
    for each row execute function forbid_inconsistent_payment_allocation_source();
create trigger trg_payment_allocation_source_append_only before update or delete on payment_allocation_source
    for each row execute function forbid_append_only_row_change();

create function forbid_allocation_sources_that_differ_from_the_allocation() returns trigger language plpgsql as $$
begin
    if (select coalesce(sum(s.amount), 0) from payment_allocation_source s where s.payment_allocation_id = new.payment_allocation_id)
       <> (select a.amount from payment_allocation a where a.id = new.payment_allocation_id) then
        raise exception 'the sources of allocation % must add up to its amount', new.payment_allocation_id
            using errcode = 'integrity_constraint_violation';
    end if;
    return null;
end;
$$;

create constraint trigger trg_payment_allocation_source_adds_up after insert on payment_allocation_source
    deferrable initially deferred for each row execute function forbid_allocation_sources_that_differ_from_the_allocation();
