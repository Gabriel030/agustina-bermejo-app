create table scholarship (
    id bigint generated by default as identity,
    course_enrollment_id bigint references course_enrollment,
    program_enrollment_id bigint references program_enrollment,
    value jsonb not null,
    reason varchar(500) not null,
    status varchar(20) not null default 'ACTIVE',
    granted_by_id bigint not null references person,
    granted_at timestamp(6) not null,
    primary key (id),
    constraint chk_scholarship_billable check (
        num_nonnulls(course_enrollment_id, program_enrollment_id) = 1
    )
);

create index ix_scholarship_course_enrollment on scholarship (course_enrollment_id);
create index ix_scholarship_program_enrollment on scholarship (program_enrollment_id);

create unique index uk_scholarship_active_course_enrollment
    on scholarship (course_enrollment_id) where status = 'ACTIVE';
create unique index uk_scholarship_active_program_enrollment
    on scholarship (program_enrollment_id) where status = 'ACTIVE';

create table scholarship_installment (
    id bigint generated by default as identity,
    scholarship_id bigint not null references scholarship,
    status varchar(20) not null default 'PENDING',
    invoice_id bigint references invoice,
    applied_at timestamp(6),
    cancelled_reason varchar(500),
    cancelled_at timestamp(6),
    primary key (id)
);

create index ix_scholarship_installment_scholarship on scholarship_installment (scholarship_id);
create index ix_scholarship_installment_invoice on scholarship_installment (invoice_id);
