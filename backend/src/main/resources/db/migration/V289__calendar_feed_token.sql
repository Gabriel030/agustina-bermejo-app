create table calendar_feed_token (
    id bigint generated by default as identity primary key,
    student_id bigint not null references student (id),
    token_hash varchar(64) not null,
    created_at timestamp not null,
    revoked_at timestamp,
    last_used_at timestamp,
    constraint uk_calendar_feed_token_hash unique (token_hash)
);

create unique index uk_calendar_feed_token_active_student on calendar_feed_token (student_id) where revoked_at is null;

do $$
declare
    action_literals text;
begin
    select string_agg(distinct quote_literal(m[1]), ', ') into action_literals
    from pg_constraint c, regexp_matches(pg_get_constraintdef(c.oid), '''([A-Z_]+)''', 'g') as m
    where c.conname = 'ck_audit_log_action' and c.conrelid = 'audit_log'::regclass;
    execute 'alter table audit_log drop constraint ck_audit_log_action';
    execute 'alter table audit_log add constraint ck_audit_log_action check (action in (' || action_literals || ', ''CALENDAR_FEED_TOKEN_ROTATED'', ''CALENDAR_FEED_TOKEN_REVOKED''))';
end $$;
