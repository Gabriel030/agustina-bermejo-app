-- Spec Estructura académica. Un ElectiveGroup es reusable entre carreras; el rango
-- mínimo/máximo que exige CADA carrera sobre un grupo vive en la tabla de asociación
-- program_elective_group, no en elective_group.
create table elective_group (
    id bigint generated by default as identity,
    name varchar(255) not null,
    description varchar(500),
    primary key (id),
    constraint uk_elective_group_name unique (name)
);

alter table program_subject add column elective_group_id bigint
    references elective_group (id);

create table program_elective_group (
    id bigint generated by default as identity,
    program_id bigint not null,
    elective_group_id bigint not null,
    min_required integer not null,
    max_allowed integer not null,
    primary key (id),
    constraint uk_program_elective_group unique (program_id, elective_group_id),
    constraint fk_program_elective_group_program foreign key (program_id)
        references program on delete cascade,
    constraint fk_program_elective_group_group foreign key (elective_group_id)
        references elective_group,
    constraint chk_program_elective_group_range
        check (min_required >= 0 and max_allowed >= min_required)
);
