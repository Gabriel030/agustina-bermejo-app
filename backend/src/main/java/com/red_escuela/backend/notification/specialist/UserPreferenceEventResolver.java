package com.red_escuela.backend.notification.specialist;

import com.red_escuela.backend.identity.entity.NotificationEvent;
import com.red_escuela.backend.notification.entity.NotificationType;

import java.util.Optional;

public final class UserPreferenceEventResolver {

    private UserPreferenceEventResolver() {
    }

    public static Optional<NotificationEvent> resolve(NotificationType type) {
        return switch (type) {
            case ANNOUNCEMENT_PUBLISHED, ANNOUNCEMENT_UPDATED -> Optional.of(NotificationEvent.INSTITUTIONAL_NOTICE);
            case EXAM_BOARD_RESCHEDULED, EXAM_BOARD_CANCELED -> Optional.of(NotificationEvent.EXAM_BOARD_REGISTERED);
            case GRADES_PUBLISHED, GRADE_CORRECTED -> Optional.of(NotificationEvent.GRADE_POSTED);
            case COURSE_WAITLIST_EXPIRED, PROGRAM_APPLICATION_APPROVED -> Optional.of(NotificationEvent.SUBJECT_ENROLLMENT);
            case COLLECTION_REMINDER -> Optional.of(NotificationEvent.PAYMENT_DUE_SOON);
            case HOLIDAYS_MISSING_FOR_NEXT_YEAR -> Optional.of(NotificationEvent.HOLIDAY_CALENDAR_REMINDER);
            case SECTION_EVAL_CONFIG_PROPOSED, SECTION_EVAL_CONFIG_APPROVED, SECTION_EVAL_CONFIG_REJECTED,
                 SECTION_EVAL_CONFIG_REMINDER, OFFER_CYCLE_SUBMITTED, OFFER_CYCLE_APPROVED, OFFER_CYCLE_REJECTED, ATTENDANCE_CHANGE_REQUEST_APPROVED, ATTENDANCE_CHANGE_REQUEST_REJECTED,
                 ATTENDANCE_JUSTIFICATION_APPROVED, ATTENDANCE_JUSTIFICATION_REJECTED, GRADUATION_REQUEST_CREATED,
                 GRADUATION_REQUEST_PENDING_REVIEW, GRADUATION_REQUEST_VERIFIED, GRADUATION_REQUEST_DEBT_BLOCKED, GRADUATION_REQUEST_APPROVED,
                 GRADUATION_REQUEST_REJECTED, GRADUATION_REQUEST_OUTDATED, SUBJECT_APPROVAL_REVERTED, DIRECTOR_APPROVAL_REQUEST_APPROVED, DIRECTOR_APPROVAL_REQUEST_REJECTED,
                 SUSPENSION_LIFTED, PAYMENT_RECEIPT_APPROVED, PAYMENT_RECEIPT_REJECTED, ENROLLMENT_FEE_EXEMPTION_GRANTED,
                 ENROLLMENT_FEE_EXEMPTION_REVOKED, LATE_PAYMENT_SETTINGS_CREATED, AUTHORIZATION_REQUESTED,
                 AUTHORIZATION_REQUEST_EXPIRED, CONFIGURATION_CHANGE_APPROVED, CONFIGURATION_CHANGE_REJECTED,
                 CONFIGURATION_VERSION_CANCELLED, PRICE_CHANGE_APPROVED, PRICE_CHANGE_REJECTED, PROGRAM_ENROLLMENT_STALLED, PROGRAM_APPLICATION_RECEIVED,
                 PAYMENT_LEFT_AS_ACCOUNT_CREDIT, GATEWAY_PAYMENT_WITH_GATEWAY_OFF, PAYMENT_RECEIPT_APPLIED_TO_OLDER_DEBT,
                 PAYMENT_CHARGED_BACK, CREDIT_NOTE_ISSUED, LATE_FEE_ISSUED, LATE_FEE_ISSUED_AFTER_FISCAL_WINDOW,
                 LATE_FEE_CORRECTION_AFTER_FISCAL_WINDOW, OVERDUE_CONTACT_LIST_UPDATED, DISCOUNT_QUOTA_EXHAUSTED,
                 PAYMENT_RECEIPT_REVIEW_OVERDUE, INCONSISTENT_ACCOUNT_DETECTED, NIGHTLY_RUN_FAILED, NIGHTLY_RUN_MISSED,
                 NIGHTLY_RUN_COMPLETED_WITH_ERRORS, MONTHLY_INVOICE_RUN_MISSED, MONTHLY_INVOICE_ITEM_RETRIES_EXHAUSTED, DRAFT_INVOICES_AWAITING_REVIEW,
                 CLOSURE_APPROVED, CLOSURE_APPROVED_SUMMARY, CLOSURE_REOPENED, CLOSURE_EXCEPTION_GRANTED, CLOSURE_CONFIRMATION_REMINDER, STUDENT_REACTIVATED ->
                    Optional.empty();
        };
    }
}
